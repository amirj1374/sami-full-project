-- Tenants (the SaaS isolation root). On-premise installs run a single tenant.
CREATE TABLE tenants (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code          VARCHAR(64)  NOT NULL,
    name          VARCHAR(160) NOT NULL,
    description   VARCHAR(2000),
    status_id     BIGINT       NOT NULL,
    contact_email VARCHAR(255),
    config        JSONB        NOT NULL DEFAULT '{}'::jsonb,
    activated_at  TIMESTAMPTZ,
    suspended_at  TIMESTAMPTZ,
    created_by    BIGINT,
    created_by_email VARCHAR(255),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_tenants PRIMARY KEY (id),
    CONSTRAINT uq_tenants_code UNIQUE (code),
    CONSTRAINT fk_tenants_status FOREIGN KEY (status_id) REFERENCES licensing_statuses (id)
);

-- Feature catalogue: the unit business modules gate on.
CREATE TABLE features (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code             VARCHAR(128) NOT NULL,
    name             VARCHAR(160) NOT NULL,
    description      VARCHAR(1000),
    module_code      VARCHAR(64),
    license_required BOOLEAN      NOT NULL DEFAULT TRUE,
    is_core          BOOLEAN      NOT NULL DEFAULT FALSE,  -- survives 'limited' expiry mode
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    is_system        BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order    INTEGER      NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_features PRIMARY KEY (id),
    CONSTRAINT uq_features_code UNIQUE (code)
);
CREATE INDEX idx_features_module ON features (module_code);

-- Feature dependency graph (validated to reject cycles / missing prerequisites).
CREATE TABLE feature_dependencies (
    feature_id    BIGINT NOT NULL,
    depends_on_id BIGINT NOT NULL,
    CONSTRAINT pk_feature_dependencies PRIMARY KEY (feature_id, depends_on_id),
    CONSTRAINT fk_feature_dep_feature FOREIGN KEY (feature_id) REFERENCES features (id) ON DELETE CASCADE,
    CONSTRAINT fk_feature_dep_target  FOREIGN KEY (depends_on_id) REFERENCES features (id) ON DELETE CASCADE,
    CONSTRAINT ck_feature_dep_self CHECK (feature_id <> depends_on_id)
);

