-- License, Subscription, Tenant & Feature Management — the licensing control
-- plane for SAMI ERP. Business modules never implement licensing logic: they ask
-- this module whether a feature is available (`@features.enabled('...')`) and
-- register usage meters. Everything is configuration: statuses, license types,
-- limit types, expiry behaviours, features, plans and their limits are rows.
-- Works unchanged for on-premise and cloud/SaaS (multi-tenant) deployments.

-- One configurable status catalogue scoped per aggregate (LICENSE|TENANT|PLAN),
-- so new statuses never require a schema change.
CREATE TABLE licensing_statuses (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    scope             VARCHAR(16)  NOT NULL,
    code              VARCHAR(64)  NOT NULL,
    name              VARCHAR(100) NOT NULL,
    is_default        BOOLEAN      NOT NULL DEFAULT FALSE,
    grants_access     BOOLEAN      NOT NULL DEFAULT FALSE,  -- licensed functionality allowed
    is_expired_state  BOOLEAN      NOT NULL DEFAULT FALSE,
    is_grace_state    BOOLEAN      NOT NULL DEFAULT FALSE,
    is_blocked_state  BOOLEAN      NOT NULL DEFAULT FALSE,
    is_system         BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order     INTEGER      NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_licensing_statuses PRIMARY KEY (id),
    CONSTRAINT uq_licensing_statuses_scope_code UNIQUE (scope, code),
    CONSTRAINT ck_licensing_statuses_scope CHECK (scope IN ('LICENSE', 'TENANT', 'PLAN'))
);
CREATE UNIQUE INDEX uq_licensing_statuses_default ON licensing_statuses (scope) WHERE is_default;

