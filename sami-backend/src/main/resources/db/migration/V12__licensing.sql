-- The licence itself.
CREATE TABLE licenses (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    license_key            VARCHAR(255) NOT NULL,
    code                   VARCHAR(64)  NOT NULL,
    license_type_id        BIGINT       NOT NULL,
    tenant_id              BIGINT       NOT NULL,
    company_id             BIGINT,                    -- null = shared by all companies in the tenant
    status_id              BIGINT       NOT NULL,
    plan_id                BIGINT       NOT NULL,
    expiry_behavior_id     BIGINT,
    activation_date        TIMESTAMPTZ,
    expiration_date        TIMESTAMPTZ,
    grace_days             INTEGER      NOT NULL DEFAULT 0,
    activated_at           TIMESTAMPTZ,
    activation_fingerprint VARCHAR(255),              -- blocks duplicate/foreign activation
    limit_overrides        JSONB        NOT NULL DEFAULT '{}'::jsonb,
    notes                  VARCHAR(2000),
    created_by             BIGINT,
    created_by_email       VARCHAR(255),
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version                BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_licenses PRIMARY KEY (id),
    CONSTRAINT uq_licenses_key  UNIQUE (license_key),
    CONSTRAINT uq_licenses_code UNIQUE (code),
    CONSTRAINT fk_licenses_type     FOREIGN KEY (license_type_id) REFERENCES license_types (id),
    CONSTRAINT fk_licenses_tenant   FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_licenses_status   FOREIGN KEY (status_id) REFERENCES licensing_statuses (id),
    CONSTRAINT fk_licenses_plan     FOREIGN KEY (plan_id) REFERENCES subscription_plans (id),
    CONSTRAINT fk_licenses_behavior FOREIGN KEY (expiry_behavior_id) REFERENCES expiry_behaviors (id)
);
CREATE INDEX idx_licenses_tenant  ON licenses (tenant_id);
CREATE INDEX idx_licenses_status  ON licenses (status_id);
CREATE INDEX idx_licenses_expiry  ON licenses (expiration_date);

-- Per-licence feature overrides: enable/disable without touching the plan and
-- without a deployment or restart.
CREATE TABLE license_features (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    license_id BIGINT  NOT NULL,
    feature_id BIGINT  NOT NULL,
    enabled    BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version    BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT pk_license_features PRIMARY KEY (id),
    CONSTRAINT uq_license_features UNIQUE (license_id, feature_id),
    CONSTRAINT fk_license_features_license FOREIGN KEY (license_id) REFERENCES licenses (id) ON DELETE CASCADE,
    CONSTRAINT fk_license_features_feature FOREIGN KEY (feature_id) REFERENCES features (id) ON DELETE CASCADE
);

-- Measured usage per tenant/limit/period (period_key '' = lifetime counter).
CREATE TABLE usage_counters (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id     BIGINT      NOT NULL,
    limit_type_id BIGINT      NOT NULL,
    period_key    VARCHAR(32) NOT NULL DEFAULT '',
    current_value BIGINT      NOT NULL DEFAULT 0,
    recorded_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    version       BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT pk_usage_counters PRIMARY KEY (id),
    CONSTRAINT uq_usage_counters UNIQUE (tenant_id, limit_type_id, period_key),
    CONSTRAINT fk_usage_counters_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_usage_counters_type   FOREIGN KEY (limit_type_id) REFERENCES usage_limit_types (id)
);

-- Append-only audit trail (old/new snapshots).
CREATE TABLE license_audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    entity_type VARCHAR(32)  NOT NULL,   -- LICENSE | TENANT | PLAN | FEATURE | USAGE
    entity_id   BIGINT,
    action      VARCHAR(64)  NOT NULL,
    old_values  JSONB,
    new_values  JSONB,
    actor_id    BIGINT,
    actor_email VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_license_audit_log PRIMARY KEY (id)
);
CREATE INDEX idx_license_audit_entity ON license_audit_log (entity_type, entity_id);

