-- Subscription plans (configurable bundles of features + limits).
CREATE TABLE subscription_plans (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code            VARCHAR(64)  NOT NULL,
    name            VARCHAR(160) NOT NULL,
    description     VARCHAR(2000),
    status_id       BIGINT       NOT NULL,
    duration_days   INTEGER      NOT NULL DEFAULT 365,
    renewal_policy  VARCHAR(32)  NOT NULL DEFAULT 'MANUAL',  -- MANUAL | AUTO | NONE
    price_config    JSONB        NOT NULL DEFAULT '{}'::jsonb,
    is_default      BOOLEAN      NOT NULL DEFAULT FALSE,
    is_system       BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order   INTEGER      NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_subscription_plans PRIMARY KEY (id),
    CONSTRAINT uq_subscription_plans_code UNIQUE (code),
    CONSTRAINT fk_subscription_plans_status FOREIGN KEY (status_id) REFERENCES licensing_statuses (id)
);
CREATE UNIQUE INDEX uq_subscription_plans_default ON subscription_plans (is_default) WHERE is_default;

CREATE TABLE plan_features (
    plan_id    BIGINT NOT NULL,
    feature_id BIGINT NOT NULL,
    CONSTRAINT pk_plan_features PRIMARY KEY (plan_id, feature_id),
    CONSTRAINT fk_plan_features_plan    FOREIGN KEY (plan_id) REFERENCES subscription_plans (id) ON DELETE CASCADE,
    CONSTRAINT fk_plan_features_feature FOREIGN KEY (feature_id) REFERENCES features (id) ON DELETE CASCADE
);

CREATE TABLE plan_limits (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    plan_id       BIGINT NOT NULL,
    limit_type_id BIGINT NOT NULL,
    limit_value   BIGINT NOT NULL,          -- -1 = unlimited
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    version       BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT pk_plan_limits PRIMARY KEY (id),
    CONSTRAINT uq_plan_limits UNIQUE (plan_id, limit_type_id),
    CONSTRAINT fk_plan_limits_plan  FOREIGN KEY (plan_id) REFERENCES subscription_plans (id) ON DELETE CASCADE,
    CONSTRAINT fk_plan_limits_type  FOREIGN KEY (limit_type_id) REFERENCES usage_limit_types (id)
);

