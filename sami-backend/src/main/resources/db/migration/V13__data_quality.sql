-- Data Quality & Validation Management — enterprise data governance for the whole
-- ERP. Business modules never implement validation logic: they submit an entity
-- payload and this module evaluates the configured rules. A rule is data
-- (validation_type + JSON config + condition tree); the validators, duplicate
-- matchers and candidate providers behind them are plugin beans, so new rule
-- kinds and dimensions never require a core change.

-- Configurable rule lifecycle statuses.
CREATE TABLE quality_statuses (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code              VARCHAR(64)  NOT NULL,
    name              VARCHAR(100) NOT NULL,
    is_default        BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active_state   BOOLEAN      NOT NULL DEFAULT FALSE,   -- rule participates in validation
    is_archived_state BOOLEAN      NOT NULL DEFAULT FALSE,
    is_system         BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order     INTEGER      NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_quality_statuses PRIMARY KEY (id),
    CONSTRAINT uq_quality_statuses_code UNIQUE (code)
);
CREATE UNIQUE INDEX uq_quality_statuses_default  ON quality_statuses (is_default)        WHERE is_default;
CREATE UNIQUE INDEX uq_quality_statuses_archived ON quality_statuses (is_archived_state) WHERE is_archived_state;

