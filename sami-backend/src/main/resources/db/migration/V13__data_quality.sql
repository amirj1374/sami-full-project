-- The rule: configuration only. `validation_type` resolves to a ValidationRule
-- bean; `config` carries its parameters; `condition_config` makes the rule
-- conditional; `weight` feeds the score.
CREATE TABLE quality_rules (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code             VARCHAR(64)  NOT NULL,
    name             VARCHAR(160) NOT NULL,
    description      VARCHAR(2000),
    module_code      VARCHAR(64)  NOT NULL,
    entity_code      VARCHAR(64)  NOT NULL,
    category         VARCHAR(64),
    priority         INTEGER      NOT NULL DEFAULT 100,
    status_id        BIGINT       NOT NULL,
    severity_id      BIGINT       NOT NULL,
    dimension_id     BIGINT,
    validation_type  VARCHAR(128) NOT NULL,
    target_field     VARCHAR(128),
    config           JSONB        NOT NULL DEFAULT '{}'::jsonb,
    condition_config JSONB        NOT NULL DEFAULT '{}'::jsonb,
    weight           NUMERIC(6,2) NOT NULL DEFAULT 1,
    company_id       BIGINT,
    tenant_id        BIGINT,
    created_by       BIGINT,
    created_by_email VARCHAR(255),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_quality_rules PRIMARY KEY (id),
    CONSTRAINT uq_quality_rules_code UNIQUE (code),
    CONSTRAINT fk_quality_rules_status    FOREIGN KEY (status_id) REFERENCES quality_statuses (id),
    CONSTRAINT fk_quality_rules_severity  FOREIGN KEY (severity_id) REFERENCES quality_severities (id),
    CONSTRAINT fk_quality_rules_dimension FOREIGN KEY (dimension_id) REFERENCES quality_dimensions (id)
);
CREATE INDEX idx_quality_rules_target ON quality_rules (module_code, entity_code);
CREATE INDEX idx_quality_rules_status ON quality_rules (status_id);

-- One validation run over one entity instance (or a batch item).
CREATE TABLE validation_runs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    run_number     VARCHAR(40)  NOT NULL,
    module_code    VARCHAR(64)  NOT NULL,
    entity_code    VARCHAR(64)  NOT NULL,
    entity_id      BIGINT,
    status         VARCHAR(32)  NOT NULL,    -- PASSED | FAILED
    rule_count     INTEGER      NOT NULL DEFAULT 0,
    passed_count   INTEGER      NOT NULL DEFAULT 0,
    failed_count   INTEGER      NOT NULL DEFAULT 0,
    score          NUMERIC(6,2),
    band_code      VARCHAR(64),
    blocking       BOOLEAN      NOT NULL DEFAULT FALSE,
    payload        JSONB,
    started_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ended_at       TIMESTAMPTZ,
    duration_ms    BIGINT,
    executed_by    BIGINT,
    executed_by_email VARCHAR(255),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_validation_runs PRIMARY KEY (id),
    CONSTRAINT uq_validation_runs_number UNIQUE (run_number)
);
CREATE INDEX idx_validation_runs_target ON validation_runs (module_code, entity_code, entity_id);
CREATE INDEX idx_validation_runs_started ON validation_runs (started_at DESC);

CREATE SEQUENCE validation_run_seq START 1;

-- A detected problem. Append-only until explicitly resolved/ignored.
CREATE TABLE quality_issues (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    run_id          BIGINT,
    rule_id         BIGINT,
    module_code     VARCHAR(64)  NOT NULL,
    entity_code     VARCHAR(64)  NOT NULL,
    entity_id       BIGINT,
    field_name      VARCHAR(128),
    severity_code   VARCHAR(64)  NOT NULL,
    dimension_code  VARCHAR(64),
    message         VARCHAR(1000) NOT NULL,
    detail          JSONB,
    status          VARCHAR(32)  NOT NULL DEFAULT 'OPEN',  -- OPEN | RESOLVED | IGNORED
    resolution_note VARCHAR(1000),
    resolved_at     TIMESTAMPTZ,
    resolved_by     BIGINT,
    resolved_by_email VARCHAR(255),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_quality_issues PRIMARY KEY (id),
    CONSTRAINT fk_quality_issues_run  FOREIGN KEY (run_id) REFERENCES validation_runs (id) ON DELETE SET NULL,
    CONSTRAINT fk_quality_issues_rule FOREIGN KEY (rule_id) REFERENCES quality_rules (id) ON DELETE SET NULL
);
CREATE INDEX idx_quality_issues_target ON quality_issues (module_code, entity_code, entity_id);
CREATE INDEX idx_quality_issues_status ON quality_issues (status, severity_code);

-- A correction applied to fix an issue (manual or automatic).
CREATE TABLE quality_corrections (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    issue_id       BIGINT       NOT NULL,
    field_name     VARCHAR(128),
    old_value      VARCHAR(2000),
    new_value      VARCHAR(2000),
    automatic      BOOLEAN      NOT NULL DEFAULT FALSE,
    note           VARCHAR(1000),
    applied_by     BIGINT,
    applied_by_email VARCHAR(255),
    applied_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_quality_corrections PRIMARY KEY (id),
    CONSTRAINT fk_quality_corrections_issue FOREIGN KEY (issue_id) REFERENCES quality_issues (id) ON DELETE CASCADE
);

-- Historical scores per module/entity/dimension for trend analysis.
CREATE TABLE quality_scores (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    module_code    VARCHAR(64)  NOT NULL,
    entity_code    VARCHAR(64)  NOT NULL,
    dimension_code VARCHAR(64),
    score          NUMERIC(6,2) NOT NULL,
    band_code      VARCHAR(64),
    sample_size    INTEGER      NOT NULL DEFAULT 0,
    detail         JSONB,
    computed_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_quality_scores PRIMARY KEY (id)
);
CREATE INDEX idx_quality_scores_target ON quality_scores (module_code, entity_code, computed_at DESC);

-- Append-only audit trail.
CREATE TABLE quality_audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    entity_type VARCHAR(32)  NOT NULL,   -- RULE | ISSUE | CORRECTION | RUN
    entity_id   BIGINT,
    action      VARCHAR(64)  NOT NULL,
    old_values  JSONB,
    new_values  JSONB,
    actor_id    BIGINT,
    actor_email VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_quality_audit_log PRIMARY KEY (id)
);
CREATE INDEX idx_quality_audit_entity ON quality_audit_log (entity_type, entity_id);

