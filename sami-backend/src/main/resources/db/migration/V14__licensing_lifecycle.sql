-- Additional permissions for the extended lifecycle.
INSERT INTO permissions (module_id, action, code, name, is_system)
SELECT m.id, a.action, m.code || ':' || a.action, m.name || ' — ' || a.label, TRUE
FROM modules m
CROSS JOIN (VALUES
    ('transfer',        'Transfer licences'),
    ('emergency',       'Emergency activation'),
    ('manage-billing',  'Manage billing and payment status')
) AS a(action, label)
WHERE m.code = 'licensing';
