-- Append-only licence transfer history (tenant/installation moves).
CREATE TABLE license_transfers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    license_id      BIGINT      NOT NULL,
    from_tenant_id  BIGINT,
    to_tenant_id    BIGINT      NOT NULL,
    from_fingerprint VARCHAR(255),
    reason          VARCHAR(1000),
    transferred_by  BIGINT,
    transferred_by_email VARCHAR(255),
    transferred_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    version         BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT pk_license_transfers PRIMARY KEY (id),
    CONSTRAINT fk_license_transfers_license FOREIGN KEY (license_id) REFERENCES licenses (id) ON DELETE CASCADE,
    CONSTRAINT fk_license_transfers_to      FOREIGN KEY (to_tenant_id) REFERENCES tenants (id)
);
CREATE INDEX idx_license_transfers_license ON license_transfers (license_id, transferred_at DESC);

