-- Licensing lifecycle extensions: feature states, billing cycle & payment
-- status, activation modes (online / offline / emergency), auto-renewal,
-- licence transfer and integration limits. Additive to V12 — all new behaviour
-- is again expressed as configurable rows plus plugin keys.

-- Feature lifecycle states. `grants_access` decides whether the gate may pass;
-- the other flags drive trial windows, beta opt-in, catalogue visibility and
-- deprecation warnings. New states are rows.
CREATE TABLE feature_states (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code           VARCHAR(64)  NOT NULL,
    name           VARCHAR(100) NOT NULL,
    description    VARCHAR(255),
    grants_access  BOOLEAN      NOT NULL DEFAULT FALSE,
    requires_optin BOOLEAN      NOT NULL DEFAULT FALSE,  -- beta: tenant must opt in
    is_trial       BOOLEAN      NOT NULL DEFAULT FALSE,  -- time-boxed by trial_days
    is_premium     BOOLEAN      NOT NULL DEFAULT FALSE,  -- must be in the plan bundle
    is_deprecated  BOOLEAN      NOT NULL DEFAULT FALSE,
    is_hidden      BOOLEAN      NOT NULL DEFAULT FALSE,  -- omitted from catalogues
    is_default     BOOLEAN      NOT NULL DEFAULT FALSE,
    is_system      BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order  INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_feature_states PRIMARY KEY (id),
    CONSTRAINT uq_feature_states_code UNIQUE (code)
);
CREATE UNIQUE INDEX uq_feature_states_default ON feature_states (is_default) WHERE is_default;

