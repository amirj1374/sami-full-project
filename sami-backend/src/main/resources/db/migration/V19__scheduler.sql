INSERT INTO permissions (module_id, action, code, name, is_system)
SELECT m.id, a.action, m.code || ':' || a.action, m.name || ' — ' || a.label, TRUE
FROM modules m
CROSS JOIN (VALUES
    ('view',    'View scheduled jobs'),
    ('create',  'Create scheduled jobs'),
    ('edit',    'Edit scheduled jobs'),
    ('delete',  'Delete scheduled jobs'),
    ('execute', 'Run jobs manually'),
    ('export',  'Export execution history')
) AS a(action, label)
WHERE m.code = 'scheduler';
