-- =====================================================================
-- V20 — Knowledge Base & SOP Management (module 13)
--
-- Centralised organisational knowledge: articles, standard operating
-- procedures, policies, work instructions, troubleshooting guides, FAQs.
--
-- This is NOT a document management system and NOT a file store. Article
-- CONTENT lives here; article ATTACHMENTS are references into the files
-- module (V18) by file UUID — no bytes are ever stored in this module.
--
-- Behaviour is data: statuses, categories, relation types, risk levels,
-- approval stages and step types are all configuration rows with
-- behavioural flags. A new category ("Trade-In Evaluation Guide") or a new
-- approval stage is an INSERT, never a release.
--
-- FULL-TEXT SEARCH NOTE. PostgreSQL ships no Persian (Farsi) text search
-- configuration — the closest, 'arabic', shares the script but stems a
-- different language and would produce wrong matches. Persian therefore
-- uses 'simple' (correct tokenisation, no stemming) and English uses
-- 'english'. The choice is driven by kb_articles.language, so replacing
-- 'simple' with a real Persian dictionary later is a configuration change
-- rather than a migration.
-- =====================================================================


