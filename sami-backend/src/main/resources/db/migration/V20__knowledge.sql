-- ---------------------------------------------------------------------
-- Versions. Published versions are immutable: content is edited on a draft
-- version and publication swaps the pointer, so a procedure someone
-- followed last year can still be produced exactly as it stood.
-- ---------------------------------------------------------------------
CREATE TABLE kb_article_versions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    article_id       BIGINT       NOT NULL,
    version_major    INTEGER      NOT NULL DEFAULT 1,
    version_minor    INTEGER      NOT NULL DEFAULT 0,
    label            VARCHAR(32)  NOT NULL,
    content          TEXT,
    content_format   VARCHAR(32)  NOT NULL DEFAULT 'markdown',
    change_note      VARCHAR(2000),
    is_current       BOOLEAN      NOT NULL DEFAULT FALSE,
    is_published     BOOLEAN      NOT NULL DEFAULT FALSE,
    published_at     TIMESTAMPTZ,
    published_by     BIGINT,
    archived_at      TIMESTAMPTZ,
    created_by       BIGINT,
    created_by_email VARCHAR(255),
    tenant_id        BIGINT       NOT NULL DEFAULT tenancy_default_tenant_id(),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_kb_article_versions PRIMARY KEY (id),
    CONSTRAINT uq_kb_article_versions UNIQUE (article_id, version_major, version_minor),
    CONSTRAINT uq_kb_article_versions_label UNIQUE (article_id, label),
    CONSTRAINT ck_kb_content_format CHECK (content_format IN ('markdown', 'html', 'text')),
    CONSTRAINT fk_kb_versions_article FOREIGN KEY (article_id) REFERENCES kb_articles (id) ON DELETE CASCADE,
    CONSTRAINT fk_kb_versions_tenant  FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE RESTRICT
);
CREATE INDEX idx_kb_versions_article ON kb_article_versions (article_id);
-- Exactly one draft-in-progress and one published version per article.
CREATE UNIQUE INDEX uq_kb_versions_current   ON kb_article_versions (article_id) WHERE is_current;
CREATE UNIQUE INDEX uq_kb_versions_published ON kb_article_versions (article_id) WHERE is_published;

ALTER TABLE kb_articles ADD CONSTRAINT fk_kb_articles_current_version
    FOREIGN KEY (current_version_id) REFERENCES kb_article_versions (id) ON DELETE SET NULL;
ALTER TABLE kb_articles ADD CONSTRAINT fk_kb_articles_published_version
    FOREIGN KEY (published_version_id) REFERENCES kb_article_versions (id) ON DELETE SET NULL;


