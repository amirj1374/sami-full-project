-- Article → article, or article → any business record. One table for both,
-- because "related to this repair" and "related to this article" are the
-- same navigational need from the reader's point of view.
CREATE TABLE kb_relations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    article_id       BIGINT       NOT NULL,
    relation_type_id BIGINT       NOT NULL,
    target_article_id BIGINT,
    target_module    VARCHAR(64),
    target_entity    VARCHAR(64),
    target_record_id BIGINT,
    note             VARCHAR(500),
    display_order    INTEGER      NOT NULL DEFAULT 0,
    tenant_id        BIGINT       NOT NULL DEFAULT tenancy_default_tenant_id(),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_kb_relations PRIMARY KEY (id),
    -- A relation must point at exactly one kind of thing.
    CONSTRAINT ck_kb_relations_target CHECK (
