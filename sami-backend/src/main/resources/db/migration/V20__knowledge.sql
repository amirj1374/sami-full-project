-- =====================================================================
-- Full-text search
--
-- The configuration is chosen from the article's language. PostgreSQL has
-- no Persian dictionary, so Persian uses 'simple': correct tokenisation,
-- no stemming. Swapping in a real dictionary later means changing this
-- function, not the schema.
-- =====================================================================
CREATE FUNCTION kb_search_config(lang VARCHAR) RETURNS REGCONFIG
    LANGUAGE sql IMMUTABLE
    AS $$ SELECT CASE WHEN lang = 'en' THEN 'english'::regconfig ELSE 'simple'::regconfig END $$;

CREATE FUNCTION kb_refresh_search_vector() RETURNS TRIGGER
    LANGUAGE plpgsql
    AS $$
BEGIN
    NEW.search_vector :=
        setweight(to_tsvector(kb_search_config(NEW.language), coalesce(NEW.title, '')),    'A') ||
        setweight(to_tsvector(kb_search_config(NEW.language), coalesce(NEW.keywords, '')), 'B') ||
        setweight(to_tsvector(kb_search_config(NEW.language), coalesce(NEW.summary, '')),  'C') ||
        setweight(to_tsvector(kb_search_config(NEW.language), coalesce(NEW.article_code, '')), 'D');
    RETURN NEW;
END $$;

CREATE TRIGGER trg_kb_articles_search
    BEFORE INSERT OR UPDATE OF title, summary, keywords, article_code, language
    ON kb_articles
    FOR EACH ROW EXECUTE FUNCTION kb_refresh_search_vector();


