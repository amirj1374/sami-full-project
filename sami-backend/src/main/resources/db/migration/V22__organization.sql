-- =====================================================================
-- Retrofit the orphan columns
--
-- Every `company_id` / `branch_id` declared since V10 has been a bare
-- BIGINT with no referent. They are all nullable and, on any existing
-- installation, all NULL — nothing has ever written them, because there
-- was nothing to write. Adding the constraint now is therefore additive:
-- it changes no data and rejects no existing row, but from here on a
-- typo'd id fails at the database instead of silently pointing nowhere.
--
-- Left nullable on purpose. NULL keeps its established meaning of
-- "applies across the organisation" — the same convention tenant_id uses
-- for platform-wide rows. Forcing a company onto every row would break
-- global dashboard widgets and global metadata definitions.
-- =====================================================================

DO $$
DECLARE
    r RECORD;
    orphans BIGINT;
BEGIN
    FOR r IN
        SELECT c.table_name, c.column_name,
               CASE c.column_name WHEN 'company_id' THEN 'companies' ELSE 'branches' END AS target
        FROM information_schema.columns c
        JOIN information_schema.tables t
          ON t.table_schema = c.table_schema AND t.table_name = c.table_name
        WHERE c.table_schema = current_schema()
          AND c.column_name IN ('company_id', 'branch_id')
          AND t.table_type = 'BASE TABLE'
          AND c.table_name NOT IN ('companies', 'branches')
    LOOP
        -- Never add a constraint that would fail: if an installation has
        -- somehow written ids, leave the column alone and say so rather
        -- than aborting the whole migration.
        EXECUTE format(
            'SELECT count(*) FROM %I x WHERE x.%I IS NOT NULL '
            'AND NOT EXISTS (SELECT 1 FROM %I y WHERE y.id = x.%I)',
            r.table_name, r.column_name, r.target, r.column_name)
        INTO orphans;

        IF orphans > 0 THEN
            RAISE WARNING 'V22: %.% has % unresolvable value(s); FK not added',
                r.table_name, r.column_name, orphans;
            CONTINUE;
        END IF;

        EXECUTE format(
            'ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES %I (id) ON DELETE SET NULL',
            r.table_name, 'fk_' || r.table_name || '_' || r.column_name, r.column_name, r.target);
    END LOOP;
END $$;


