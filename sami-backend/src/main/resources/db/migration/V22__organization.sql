-- =====================================================================
-- Post-migration assertions. A migration that half-applied is worse than
-- one that failed, so prove the invariants before committing.
-- =====================================================================

DO $$
DECLARE
    company_count BIGINT;
    branch_count  BIGINT;
    type_count    BIGINT;
BEGIN
    SELECT count(*) INTO company_count FROM companies WHERE is_default;
    SELECT count(*) INTO branch_count  FROM branches  WHERE is_default;
    SELECT count(*) INTO type_count    FROM branch_types WHERE is_default;

    IF company_count <> 1 THEN
        RAISE EXCEPTION 'V22: expected exactly 1 default company, found %', company_count;
    END IF;
    IF branch_count <> 1 THEN
        RAISE EXCEPTION 'V22: expected exactly 1 default branch, found %', branch_count;
    END IF;
    IF type_count <> 1 THEN
        RAISE EXCEPTION 'V22: expected exactly 1 default branch type, found %', type_count;
    END IF;
END $$;
