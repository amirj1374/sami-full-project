-- ---------------------------------------------------------------------
-- Delivery behaviour, as data. Backoff is base_interval * multiplier^n
-- so "3 tries, a minute apart" and "6 tries, exponential" are both rows.
-- ---------------------------------------------------------------------
CREATE TABLE comm_delivery_policies (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code                        VARCHAR(64)  NOT NULL,
    name                        VARCHAR(100) NOT NULL,
    description                 VARCHAR(500),

    max_attempts                INTEGER      NOT NULL DEFAULT 3,
    retry_base_seconds          INTEGER      NOT NULL DEFAULT 60,
    retry_backoff_multiplier    NUMERIC(4,2) NOT NULL DEFAULT 2.0,
    retry_max_seconds           INTEGER      NOT NULL DEFAULT 3600,
    -- Per-attempt provider timeout.
    timeout_seconds             INTEGER      NOT NULL DEFAULT 30,
    -- Queued messages older than this are expired, never sent late. 0 = never.
    expiration_minutes          INTEGER      NOT NULL DEFAULT 0,

    requires_delivery_receipt   BOOLEAN      NOT NULL DEFAULT FALSE,
    requires_read_receipt       BOOLEAN      NOT NULL DEFAULT FALSE,

    is_default                  BOOLEAN      NOT NULL DEFAULT FALSE,
    is_system                   BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order               INTEGER      NOT NULL DEFAULT 0,

    tenant_id                   BIGINT,
    created_at                  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version                     BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT pk_comm_delivery_policies PRIMARY KEY (id),
    CONSTRAINT fk_comm_delivery_policies_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT ck_comm_delivery_policies_sane CHECK (
        max_attempts >= 1 AND retry_base_seconds >= 1
        AND retry_backoff_multiplier >= 1.0 AND retry_max_seconds >= retry_base_seconds
        AND timeout_seconds >= 1 AND expiration_minutes >= 0)
);
CREATE UNIQUE INDEX uq_comm_delivery_policies_code_global ON comm_delivery_policies (code) WHERE tenant_id IS NULL;
CREATE UNIQUE INDEX uq_comm_delivery_policies_code_tenant ON comm_delivery_policies (tenant_id, code) WHERE tenant_id IS NOT NULL;
CREATE UNIQUE INDEX uq_comm_delivery_policies_default ON comm_delivery_policies ((TRUE)) WHERE is_default AND tenant_id IS NULL;


-- ---------------------------------------------------------------------
-- A channel: a type served by a provider under a policy, scoped to an
-- organisation. "SMS via Gateway-A for Branch 1" and "SMS via Gateway-B
-- for Branch 2" are two rows with different priorities — which is what
-- makes provider fallback a data question.
-- ---------------------------------------------------------------------
CREATE TABLE comm_channels (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code                VARCHAR(64)  NOT NULL,
    name                VARCHAR(100) NOT NULL,
    description         VARCHAR(500),

    channel_type_id     BIGINT       NOT NULL,
    provider_id         BIGINT       NOT NULL,
    status_id           BIGINT       NOT NULL,
    delivery_policy_id  BIGINT,

    company_id          BIGINT,
    branch_id           BIGINT,

    -- Higher wins among channels of the same type when routing.
    priority            INTEGER      NOT NULL DEFAULT 0,

    -- Sender identity presented to recipients (from-address, sender id).
    sender_address      VARCHAR(255),

    tenant_id           BIGINT       NOT NULL DEFAULT tenancy_default_tenant_id(),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version             BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT pk_comm_channels PRIMARY KEY (id),
    CONSTRAINT fk_comm_channels_type FOREIGN KEY (channel_type_id) REFERENCES comm_channel_types (id),
    CONSTRAINT fk_comm_channels_provider FOREIGN KEY (provider_id) REFERENCES comm_providers (id),
    CONSTRAINT fk_comm_channels_status FOREIGN KEY (status_id) REFERENCES comm_channel_statuses (id),
    CONSTRAINT fk_comm_channels_policy FOREIGN KEY (delivery_policy_id) REFERENCES comm_delivery_policies (id),
    CONSTRAINT fk_comm_channels_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE SET NULL,
    CONSTRAINT fk_comm_channels_branch FOREIGN KEY (branch_id) REFERENCES branches (id) ON DELETE SET NULL,
    CONSTRAINT fk_comm_channels_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX uq_comm_channels_code ON comm_channels (tenant_id, code);
CREATE INDEX ix_comm_channels_type ON comm_channels (channel_type_id, priority DESC);
CREATE INDEX ix_comm_channels_branch ON comm_channels (branch_id) WHERE branch_id IS NOT NULL;


-- ---------------------------------------------------------------------
-- Routing rules: which channel type to prefer, and where to fall back,
-- optionally scoped to a calling module. Evaluated in priority order;
-- first match wins. `respect_business_hours` defers non-urgent sends to
-- the next working window via the V23 calendar — the "no marketing SMS
-- at 3 a.m." rule as a column instead of a code branch.
-- ---------------------------------------------------------------------
CREATE TABLE comm_routing_rules (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code                    VARCHAR(64)  NOT NULL,
    name                    VARCHAR(100) NOT NULL,
    description             VARCHAR(500),

    -- NULL = applies to every module.
    module_code             VARCHAR(64),
    -- Only messages at or above this priority match. 0 = all.
    min_message_priority    INTEGER      NOT NULL DEFAULT 0,

    preferred_channel_id    BIGINT       NOT NULL,
    fallback_channel_id     BIGINT,

    respect_business_hours  BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Urgent overrides: a message at/above this priority ignores business
    -- hours even when the rule respects them. 0 = never override.
    emergency_priority      INTEGER      NOT NULL DEFAULT 0,

    is_active               BOOLEAN      NOT NULL DEFAULT TRUE,
    priority                INTEGER      NOT NULL DEFAULT 0,

    tenant_id               BIGINT       NOT NULL DEFAULT tenancy_default_tenant_id(),
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version                 BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT pk_comm_routing_rules PRIMARY KEY (id),
    CONSTRAINT fk_comm_routing_pref FOREIGN KEY (preferred_channel_id) REFERENCES comm_channels (id) ON DELETE CASCADE,
    CONSTRAINT fk_comm_routing_fallback FOREIGN KEY (fallback_channel_id) REFERENCES comm_channels (id) ON DELETE SET NULL,
    CONSTRAINT fk_comm_routing_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX uq_comm_routing_rules_code ON comm_routing_rules (tenant_id, code);
CREATE INDEX ix_comm_routing_rules_eval ON comm_routing_rules (priority DESC) WHERE is_active;


-- ---------------------------------------------------------------------
-- Templates. `{{variable}}` placeholders; `variables` declares the
-- allowed names. Rendering is FAIL-CLOSED both ways: an undeclared
-- placeholder in the template and a missing value at send time are both
-- errors — a customer must never receive "Dear {{name}}".
-- ---------------------------------------------------------------------
CREATE TABLE comm_templates (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code              VARCHAR(64)  NOT NULL,
    name              VARCHAR(100) NOT NULL,
    description       VARCHAR(500),

    -- NULL = usable on any channel type.
    channel_type_id   BIGINT,
    module_code       VARCHAR(64),

    language          VARCHAR(16)  NOT NULL DEFAULT 'fa',
    subject_template  VARCHAR(500),
    body_template     TEXT         NOT NULL,
    -- Declared placeholder names, e.g. ["customerName","amount","dueDate"].
    variables         JSONB,

    -- Editing creates a new revision and deactivates the old one, so a
    -- message row's template_id always shows the exact text that was sent.
    revision          INTEGER      NOT NULL DEFAULT 1,
    is_active         BOOLEAN      NOT NULL DEFAULT TRUE,
    is_system         BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order     INTEGER      NOT NULL DEFAULT 0,

    tenant_id         BIGINT,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version           BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT pk_comm_templates PRIMARY KEY (id),
    CONSTRAINT fk_comm_templates_type FOREIGN KEY (channel_type_id) REFERENCES comm_channel_types (id) ON DELETE SET NULL,
    CONSTRAINT fk_comm_templates_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE
);
-- Uniqueness is per ACTIVE revision: history keeps the code, only one live.
CREATE UNIQUE INDEX uq_comm_templates_code_global ON comm_templates (code, language) WHERE is_active AND tenant_id IS NULL;
CREATE UNIQUE INDEX uq_comm_templates_code_tenant ON comm_templates (tenant_id, code, language) WHERE is_active AND tenant_id IS NOT NULL;


