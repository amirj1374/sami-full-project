-- =====================================================================
-- V26 — Enterprise Communication Hub & Omnichannel Messaging
--
-- The DELIVERY half of messaging: HOW a message reaches a person over a
-- channel, through which provider, with what retry/expiry behaviour, and
-- with a permanent, entity-linked record of what happened.
--
-- It is NOT a notification centre. Deciding WHAT to send and to WHOM is
-- the caller's job (the future notification module, the scheduler's
-- reminders, workflow, campaigns). This module accepts a send request
-- and owns everything after it: routing, templating, dispatch, retry,
-- fallback, tracking, history.
--
-- WHAT THIS ABSORBS (and deliberately does not duplicate):
--   * common/mail/MailSender — the password-reset port stays, but a real
--     provider now backs it through this module's SMTP handler.
--   * V24 reminder_channels — the scheduler keeps its ReminderChannelHandler
--     SPI; this module registers the handlers those inactive rows have
--     been waiting for. Activating a reminder channel is now a data flip.
--   * sup_channels (V9) is a CRM record of a supplier's PREFERRED contact
--     routes — preference data, not delivery machinery. Untouched.
--
-- Behaviour is data throughout: channel types, providers, statuses,
-- delivery policies, routing rules and templates are all configuration
-- rows resolved through SPI registries. A provider row whose handler_key
-- has no bean is inert configuration — the WhatsApp row can exist today
-- and start delivering the day its handler bean ships, with no migration.
--
-- THE OUTBOUND GUARANTEE. A message is a row FIRST, then a delivery
-- attempt (transactional-outbox shape). Dispatch failure can never lose a
-- message: the row stays queued with attempts/next_attempt_at and the
-- sweep (a V19 scheduled job, seeded draft) retries it under the
-- channel's delivery policy until it succeeds, exhausts retries, or
-- expires. Duplicate sends are stopped at the database by a unique
-- idempotency key, not by caller discipline.
-- =====================================================================


-- ---------------------------------------------------------------------
-- Channel taxonomy. Behavioural flags drive validation and capability
-- checks; no service ever tests for the string 'SMS'.
-- ---------------------------------------------------------------------
CREATE TABLE comm_channel_types (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code                   VARCHAR(64)  NOT NULL,
    name                   VARCHAR(100) NOT NULL,
    description            VARCHAR(500),
    icon                   VARCHAR(64),

    -- What a recipient address must be, and what the channel can carry.
    requires_phone         BOOLEAN      NOT NULL DEFAULT FALSE,
    requires_email         BOOLEAN      NOT NULL DEFAULT FALSE,
    requires_device_token  BOOLEAN      NOT NULL DEFAULT FALSE,
    supports_subject       BOOLEAN      NOT NULL DEFAULT FALSE,
    supports_attachments   BOOLEAN      NOT NULL DEFAULT FALSE,
    supports_conversations BOOLEAN      NOT NULL DEFAULT FALSE,
    supports_read_receipt  BOOLEAN      NOT NULL DEFAULT FALSE,
    -- 0 = unlimited. SMS is the reason this exists.
    max_body_length        INTEGER      NOT NULL DEFAULT 0,
    max_attachment_bytes   BIGINT       NOT NULL DEFAULT 0,

    is_default             BOOLEAN      NOT NULL DEFAULT FALSE,
    is_system              BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active              BOOLEAN      NOT NULL DEFAULT TRUE,
    display_order          INTEGER      NOT NULL DEFAULT 0,

    tenant_id              BIGINT,
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version                BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT pk_comm_channel_types PRIMARY KEY (id),
    CONSTRAINT fk_comm_channel_types_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT ck_comm_channel_types_limits CHECK (max_body_length >= 0 AND max_attachment_bytes >= 0)
);
CREATE UNIQUE INDEX uq_comm_channel_types_code_global ON comm_channel_types (code) WHERE tenant_id IS NULL;
CREATE UNIQUE INDEX uq_comm_channel_types_code_tenant ON comm_channel_types (tenant_id, code) WHERE tenant_id IS NOT NULL;
CREATE UNIQUE INDEX uq_comm_channel_types_default ON comm_channel_types ((TRUE)) WHERE is_default AND tenant_id IS NULL;


