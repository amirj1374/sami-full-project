-- ---------------------------------------------------------------------
-- Messages: the permanent record. Row first, delivery second.
-- ---------------------------------------------------------------------
CREATE TABLE comm_messages (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    message_number       VARCHAR(32)  NOT NULL,
    conversation_id      BIGINT,
    channel_id           BIGINT       NOT NULL,
    status_id            BIGINT       NOT NULL,
    template_id          BIGINT,

    -- OUTBOUND today; INBOUND reserved for the omnichannel-inbox future.
    direction            VARCHAR(16)  NOT NULL DEFAULT 'OUTBOUND',

    sender_user_id       BIGINT,
    recipient_address    VARCHAR(255) NOT NULL,
    customer_id          BIGINT,
    supplier_id          BIGINT,

    module_code          VARCHAR(64),
    related_entity_type  VARCHAR(64),
    related_entity_id    BIGINT,

    subject              VARCHAR(500),
    body                 TEXT         NOT NULL,
    language             VARCHAR(16)  NOT NULL DEFAULT 'fa',
    priority             INTEGER      NOT NULL DEFAULT 0,

    -- Caller-supplied dedup key; the partial unique index below is what
    -- actually prevents double delivery, not caller discipline.
    idempotency_key      VARCHAR(128),

    attempts             INTEGER      NOT NULL DEFAULT 0,
    next_attempt_at      TIMESTAMPTZ,
    last_error           VARCHAR(1000),
    provider_message_ref VARCHAR(255),

    queued_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    sent_at              TIMESTAMPTZ,
    delivered_at         TIMESTAMPTZ,
    read_at              TIMESTAMPTZ,
    failed_at            TIMESTAMPTZ,
    expires_at           TIMESTAMPTZ,

    tenant_id            BIGINT       NOT NULL DEFAULT tenancy_default_tenant_id(),
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version              BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT pk_comm_messages PRIMARY KEY (id),
    CONSTRAINT fk_comm_messages_conversation FOREIGN KEY (conversation_id) REFERENCES comm_conversations (id) ON DELETE SET NULL,
    CONSTRAINT fk_comm_messages_channel FOREIGN KEY (channel_id) REFERENCES comm_channels (id),
    CONSTRAINT fk_comm_messages_status FOREIGN KEY (status_id) REFERENCES comm_message_statuses (id),
    CONSTRAINT fk_comm_messages_template FOREIGN KEY (template_id) REFERENCES comm_templates (id) ON DELETE SET NULL,
    CONSTRAINT fk_comm_messages_sender FOREIGN KEY (sender_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_comm_messages_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE SET NULL,
    CONSTRAINT fk_comm_messages_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE SET NULL,
    CONSTRAINT fk_comm_messages_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT ck_comm_messages_direction CHECK (direction IN ('OUTBOUND', 'INBOUND'))
);
CREATE UNIQUE INDEX uq_comm_messages_number ON comm_messages (tenant_id, message_number);
-- THE dedup guard: one live message per caller-supplied key.
CREATE UNIQUE INDEX uq_comm_messages_idempotency ON comm_messages (tenant_id, idempotency_key)
    WHERE idempotency_key IS NOT NULL;
-- The sweep's working set: retryable work that is due.
CREATE INDEX ix_comm_messages_due ON comm_messages (next_attempt_at) WHERE next_attempt_at IS NOT NULL;
CREATE INDEX ix_comm_messages_conversation ON comm_messages (conversation_id) WHERE conversation_id IS NOT NULL;
CREATE INDEX ix_comm_messages_recipient ON comm_messages (recipient_address);
CREATE INDEX ix_comm_messages_customer ON comm_messages (customer_id, created_at DESC) WHERE customer_id IS NOT NULL;
CREATE INDEX ix_comm_messages_related ON comm_messages (module_code, related_entity_type, related_entity_id)
    WHERE related_entity_id IS NOT NULL;
CREATE INDEX ix_comm_messages_status ON comm_messages (status_id, created_at DESC);


