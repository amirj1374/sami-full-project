-- =====================================================================
-- Post-migration assertions
-- =====================================================================

DO $$
DECLARE
    n BIGINT;
BEGIN
    SELECT count(*) INTO n FROM comm_message_statuses WHERE is_default;
    IF n <> 1 THEN RAISE EXCEPTION 'V26: expected 1 default message status, found %', n; END IF;

    SELECT count(*) INTO n FROM comm_channel_types WHERE is_default;
    IF n <> 1 THEN RAISE EXCEPTION 'V26: expected 1 default channel type, found %', n; END IF;

    SELECT count(*) INTO n FROM comm_channels c JOIN comm_channel_statuses s ON s.id = c.status_id
    WHERE s.allows_sending;
    IF n < 1 THEN RAISE EXCEPTION 'V26: no sendable channel was seeded'; END IF;

    -- A terminal status must never be retryable, or the sweep would
    -- resurrect cancelled and expired messages forever.
    IF EXISTS (SELECT 1 FROM comm_message_statuses WHERE is_terminal AND allows_retry) THEN
        RAISE EXCEPTION 'V26: a terminal message status is flagged retryable';
    END IF;

    SELECT count(*) INTO n FROM modules WHERE code = 'communication';
    IF n <> 1 THEN RAISE EXCEPTION 'V26: module row missing'; END IF;

    SELECT count(*) INTO n FROM scheduled_jobs WHERE handler_key = 'comm-outbound-sweep';
    IF n <> 1 THEN RAISE EXCEPTION 'V26: outbound sweep job missing'; END IF;
END $$;
