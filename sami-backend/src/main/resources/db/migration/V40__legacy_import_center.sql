INSERT INTO permissions (module_id, action, code, name, is_system)
SELECT m.id, a.action, m.code || ':' || a.action, m.name || ' — ' || a.label, TRUE
FROM modules m CROSS JOIN (VALUES
 ('view','View legacy financial data'), ('create','Upload legacy archives'), ('analyze','Analyze legacy archives'),
 ('execute','Import into legacy staging'), ('compare','Run comparisons'), ('review','Review discrepancies'),
 ('delete','Delete legacy batches')) a(action,label)
WHERE m.code='legacy-import';

-- Sensitive legacy access is admin-only by default.
INSERT INTO role_permissions(role_id, permission_id)
SELECT r.id,p.id FROM roles r JOIN permissions p ON p.code LIKE 'legacy-import:%'
WHERE r.is_super_admin OR lower(r.name) IN ('admin','administrator')
ON CONFLICT DO NOTHING;
