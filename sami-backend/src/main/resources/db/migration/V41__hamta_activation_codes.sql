INSERT INTO permissions (module_id, action, code, name, is_system)
SELECT m.id, a.action, m.code || ':' || a.action, m.name || ' — ' || a.label, TRUE
FROM modules m CROSS JOIN (VALUES
 ('view','View delivery state'), ('view-code','View activation codes'),
 ('edit','Register or correct undelivered codes'), ('deliver','Deliver activation codes'),
 ('report','View operational reports'), ('settings-update','Update HAMTA settings')) a(action,label)
WHERE m.code='hamta';

INSERT INTO role_permissions(role_id, permission_id)
SELECT r.id,p.id FROM roles r JOIN permissions p ON p.code LIKE 'hamta:%'
WHERE r.is_super_admin OR lower(r.name) IN ('admin','administrator')
ON CONFLICT DO NOTHING;
