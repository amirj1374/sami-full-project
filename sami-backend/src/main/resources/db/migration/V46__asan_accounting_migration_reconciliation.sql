-- Accounting-migration evidence remains isolated from canonical operational and accounting records.
CREATE TABLE legacy_migration_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    acceptance_status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_legacy_migration_group_status CHECK (status IN ('DRAFT','ACTIVE','RECONCILING','READY_FOR_ACCEPTANCE','ACCEPTED','BLOCKED')),
    CONSTRAINT ck_legacy_migration_group_acceptance CHECK (acceptance_status IN ('PENDING','PASS','WARNING','FAIL','BLOCKED'))
);
CREATE INDEX idx_legacy_migration_groups_tenant_created ON legacy_migration_groups(tenant_id, created_at DESC);

ALTER TABLE legacy_import_batches
    ADD COLUMN migration_group_id BIGINT REFERENCES legacy_migration_groups(id) ON DELETE SET NULL,
    ADD COLUMN evidence_type VARCHAR(32) NOT NULL DEFAULT 'ASAN_BACKUP';
ALTER TABLE legacy_import_batches
    ADD CONSTRAINT ck_legacy_batch_evidence_type CHECK (evidence_type IN ('ASAN_BACKUP','ASAN_EXCEL_REPORT'));
CREATE INDEX idx_legacy_batches_group ON legacy_import_batches(tenant_id, migration_group_id, created_at);

CREATE TABLE legacy_reconciliation_exceptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    migration_group_id BIGINT NOT NULL REFERENCES legacy_migration_groups(id) ON DELETE CASCADE,
    domain VARCHAR(40) NOT NULL,
    source_key VARCHAR(300) NOT NULL,
    classification VARCHAR(40) NOT NULL,
    legacy_value JSONB NOT NULL DEFAULT '{}'::jsonb,
    sami_value JSONB NOT NULL DEFAULT '{}'::jsonb,
    difference_value JSONB NOT NULL DEFAULT '{}'::jsonb,
    explanation VARCHAR(2000),
    source_evidence JSONB NOT NULL DEFAULT '{}'::jsonb,
    reviewed_by BIGINT,
    reviewed_at TIMESTAMPTZ,
    approval_status VARCHAR(24) NOT NULL DEFAULT 'NEEDS_INVESTIGATION',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_legacy_reconciliation_exception UNIQUE(migration_group_id, domain, source_key),
    CONSTRAINT ck_legacy_reconciliation_classification CHECK (classification IN ('MATCHED','DIFFERENT','ONLY_IN_LEGACY','ONLY_IN_SAMI','AMBIGUOUS','UNMAPPED','EXPLAINED_DIFFERENCE','IGNORED')),
    CONSTRAINT ck_legacy_reconciliation_approval CHECK (approval_status IN ('NEEDS_INVESTIGATION','EXPLAINED','ACCEPTED','REJECTED'))
);
CREATE INDEX idx_legacy_reconciliation_exceptions_group ON legacy_reconciliation_exceptions(tenant_id, migration_group_id, domain, classification);

CREATE TABLE legacy_migration_acceptance_checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    migration_group_id BIGINT NOT NULL REFERENCES legacy_migration_groups(id) ON DELETE CASCADE,
    check_code VARCHAR(80) NOT NULL,
    status VARCHAR(16) NOT NULL,
    evidence JSONB NOT NULL DEFAULT '{}'::jsonb,
    reviewed_by BIGINT,
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_legacy_acceptance_check UNIQUE(migration_group_id, check_code),
    CONSTRAINT ck_legacy_acceptance_check_status CHECK (status IN ('PASS','FAIL','WARNING','PENDING'))
);
CREATE INDEX idx_legacy_acceptance_checks_group ON legacy_migration_acceptance_checks(tenant_id, migration_group_id, status);

INSERT INTO permissions (module_id, action, code, name, is_system)
SELECT m.id, a.action, m.code || ':' || a.action, m.name || ' — ' || a.label, TRUE
FROM modules m CROSS JOIN (VALUES
    ('reconcile','Run accounting reconciliation'),
    ('accept','Review migration acceptance')) a(action,label)
WHERE m.code='legacy-import'
ON CONFLICT (code) DO NOTHING;

INSERT INTO role_permissions(role_id, permission_id)
SELECT r.id,p.id FROM roles r JOIN permissions p ON p.code IN ('legacy-import:reconcile','legacy-import:accept')
WHERE r.is_super_admin OR lower(r.name) IN ('admin','administrator')
ON CONFLICT DO NOTHING;
