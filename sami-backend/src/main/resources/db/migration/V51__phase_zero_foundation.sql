CREATE INDEX ix_ucr_user_tenant ON user_company_roles(tenant_id, user_id, is_active);

CREATE TABLE user_branch_grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    assignment_id BIGINT NOT NULL REFERENCES user_company_roles(id) ON DELETE CASCADE,
