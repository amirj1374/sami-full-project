-- Phase 1 / Slice 3. Orders are additive commercial commitments.
CREATE SEQUENCE sales_order_number_seq START WITH 1;
CREATE TABLE sales_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
 company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
 branch_id BIGINT NOT NULL REFERENCES branches(id) ON DELETE RESTRICT,
 customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
 contact_id BIGINT NOT NULL REFERENCES contacts(id) ON DELETE RESTRICT,
 source_document_id BIGINT REFERENCES sales_documents(id) ON DELETE RESTRICT,
 order_number VARCHAR(48) NOT NULL,
 status VARCHAR(16) NOT NULL,
 currency VARCHAR(3) NOT NULL DEFAULT 'IRR', subtotal NUMERIC(18,2) NOT NULL DEFAULT 0,
 discount_total NUMERIC(18,2) NOT NULL DEFAULT 0, final_amount NUMERIC(18,2) NOT NULL DEFAULT 0,
 notes VARCHAR(2000), confirmed_at TIMESTAMPTZ, cancelled_at TIMESTAMPTZ,
 created_by BIGINT, created_by_email VARCHAR(255), created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT ck_sales_order_status CHECK(status IN ('DRAFT','CONFIRMED','CANCELLED')),
 CONSTRAINT ck_sales_order_amounts CHECK(subtotal>=0 AND discount_total>=0 AND final_amount>=0),
 CONSTRAINT uq_sales_order_number UNIQUE(tenant_id,order_number)
);
CREATE INDEX ix_sales_orders_scope ON sales_orders(tenant_id,company_id,branch_id,status,created_at DESC);
CREATE TABLE sales_order_lines (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES sales_orders(id) ON DELETE CASCADE,
 tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
 source_line_id BIGINT REFERENCES sales_document_lines(id) ON DELETE RESTRICT,
 product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
 product_sku VARCHAR(100) NOT NULL, product_name VARCHAR(255) NOT NULL,
 quantity NUMERIC(14,3) NOT NULL CHECK(quantity>0), unit_price NUMERIC(18,2) NOT NULL CHECK(unit_price>=0),
 discount NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK(discount>=0), line_total NUMERIC(18,2) NOT NULL CHECK(line_total>=0),
 reserved_quantity NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(reserved_quantity>=0),
 backordered_quantity NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(backordered_quantity>=0),
 fulfilled_quantity NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(fulfilled_quantity>=0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT ck_sales_order_line_quantities CHECK(reserved_quantity + backordered_quantity <= quantity AND fulfilled_quantity <= reserved_quantity)
);
CREATE INDEX ix_sales_order_lines_order ON sales_order_lines(order_id);
CREATE TABLE sales_order_audit_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES sales_orders(id) ON DELETE CASCADE,
 tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
 action VARCHAR(48) NOT NULL, actor_id BIGINT, actor_email VARCHAR(255), old_value JSONB, new_value JSONB,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(), created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX ix_sales_order_audit_history ON sales_order_audit_history(tenant_id,order_id,occurred_at DESC);
