-- P4-S5: explicit Treasury-to-Accounting mapping and auditable posting state.
CREATE TABLE treasury_accounting_mappings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
    treasury_account_id BIGINT NOT NULL REFERENCES treasury_accounts(id) ON DELETE RESTRICT,
    accounting_account_id BIGINT NOT NULL REFERENCES accounting_accounts(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_treasury_accounting_mapping UNIQUE (tenant_id, treasury_account_id)
);
CREATE INDEX ix_treasury_accounting_mapping_accounting
    ON treasury_accounting_mappings(tenant_id, accounting_account_id);

CREATE TABLE treasury_accounting_postings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
    treasury_transaction_id BIGINT NOT NULL REFERENCES treasury_transactions(id) ON DELETE RESTRICT,
    status VARCHAR(24) NOT NULL,
    journal_entry_id BIGINT REFERENCES accounting_journal_entries(id) ON DELETE RESTRICT,
    reason VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_treasury_accounting_posting UNIQUE (tenant_id, treasury_transaction_id),
    CONSTRAINT ck_treasury_accounting_posting_status CHECK (status IN ('POSTED','MISSING_MAPPING','FAILED'))
);
