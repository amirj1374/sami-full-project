-- Dedicated management permissions (spec: Manage Tags, Manage Status/config).
INSERT INTO permissions (module_id, action, code, name, is_system)
SELECT m.id, a.action, m.code || ':' || a.action, m.name || ' — ' || a.label, TRUE
FROM modules m
CROSS JOIN (VALUES
    ('manage-tags',   'Manage tags'),
    ('manage-config', 'Manage statuses, types, sources and rules')
) AS a(action, label)
WHERE m.code = 'customers';
