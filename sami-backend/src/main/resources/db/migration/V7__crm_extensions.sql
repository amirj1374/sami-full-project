-- CRM extensions: relationships, configurable preferences, blacklist,
-- segments (marketing / saved filters), and dedicated manage permissions.

-- Configurable relation types (family, partner, guarantor, emergency contact…).
CREATE TABLE crm_relation_types (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code          VARCHAR(64)  NOT NULL,
    name          VARCHAR(100) NOT NULL,
    is_system     BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order INTEGER      NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_crm_relation_types PRIMARY KEY (id),
    CONSTRAINT uq_crm_relation_types_code UNIQUE (code)
);

