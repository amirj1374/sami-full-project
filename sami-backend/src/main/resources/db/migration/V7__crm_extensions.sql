-- Blacklist: configurable reasons + an auditable entry log. The status carrying
-- is_blacklist_state (unique) is the transition target; blacklisted statuses
-- stay visible (not hidden_by_default) so blocked customers remain searchable.
CREATE TABLE crm_blacklist_reasons (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code          VARCHAR(64)  NOT NULL,
    name          VARCHAR(100) NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    is_system     BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order INTEGER      NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_crm_blacklist_reasons PRIMARY KEY (id),
    CONSTRAINT uq_crm_blacklist_reasons_code UNIQUE (code)
);

