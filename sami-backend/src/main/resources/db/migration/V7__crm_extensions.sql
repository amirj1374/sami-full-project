CREATE TABLE customer_blacklist_entries (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id      BIGINT       NOT NULL,
    reason_id        BIGINT       NOT NULL,
    note             VARCHAR(500),
    created_by       BIGINT,
    created_by_email VARCHAR(255),
    lifted_at        TIMESTAMPTZ,
    lifted_by        BIGINT,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_customer_blacklist_entries PRIMARY KEY (id),
    CONSTRAINT fk_cbe_customer FOREIGN KEY (customer_id)
        REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT fk_cbe_reason FOREIGN KEY (reason_id) REFERENCES crm_blacklist_reasons (id)
);
CREATE INDEX idx_cbe_customer ON customer_blacklist_entries (customer_id);

-- Segments: stored customer filters (marketing lists / saved searches / report
