-- Customer-to-customer relationships.
CREATE TABLE customer_relations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id         BIGINT       NOT NULL,
    related_customer_id BIGINT       NOT NULL,
    relation_type_id    BIGINT       NOT NULL,
    note                VARCHAR(255),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_customer_relations PRIMARY KEY (id),
    CONSTRAINT fk_cr_customer FOREIGN KEY (customer_id)
        REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT fk_cr_related FOREIGN KEY (related_customer_id)
        REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT fk_cr_type FOREIGN KEY (relation_type_id) REFERENCES crm_relation_types (id),
    CONSTRAINT uq_customer_relations UNIQUE (customer_id, related_customer_id, relation_type_id),
    CONSTRAINT ck_customer_relations_not_self CHECK (customer_id <> related_customer_id)
);
CREATE INDEX idx_customer_relations_customer ON customer_relations (customer_id);
CREATE INDEX idx_customer_relations_related  ON customer_relations (related_customer_id);

-- Configurable preference fields (same dynamic-field pattern as user profiles):
-- definitions are data, values live in customers.preferences (JSONB).
CREATE TABLE crm_preference_definitions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    pref_key      VARCHAR(64)  NOT NULL,
    label         VARCHAR(100) NOT NULL,
    field_type    VARCHAR(16)  NOT NULL,   -- TEXT | NUMBER | DATE | BOOLEAN | SELECT
    required      BOOLEAN      NOT NULL DEFAULT FALSE,
    min_length    INTEGER,
    max_length    INTEGER,
    pattern       VARCHAR(255),
    options       JSONB,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    display_order INTEGER      NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_crm_preference_definitions PRIMARY KEY (id),
    CONSTRAINT uq_crm_preference_definitions_key UNIQUE (pref_key)
);

