CREATE TABLE goods_receipt_unit_identifiers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
    goods_receipt_line_id BIGINT NOT NULL REFERENCES goods_receipt_lines(id) ON DELETE CASCADE,
    serial_number VARCHAR(128),
    imei VARCHAR(64),
    hamta_activation_code VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_goods_receipt_unit_identifier_identity
        CHECK (serial_number IS NOT NULL OR imei IS NOT NULL),
    CONSTRAINT uq_goods_receipt_unit_identifier_serial
        UNIQUE (tenant_id, serial_number),
    CONSTRAINT uq_goods_receipt_unit_identifier_imei
        UNIQUE (tenant_id, imei)
);
CREATE INDEX ix_goods_receipt_unit_identifiers_line
    ON goods_receipt_unit_identifiers(tenant_id, goods_receipt_line_id);

