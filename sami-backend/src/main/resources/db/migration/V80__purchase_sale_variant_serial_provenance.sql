ALTER TABLE sales_order_lines ADD COLUMN serial_number VARCHAR(128);
ALTER TABLE sales_order_lines ADD COLUMN imei VARCHAR(64);

ALTER TABLE purchase_order_lines ADD COLUMN variant_id BIGINT;
ALTER TABLE purchase_order_lines
    ADD CONSTRAINT fk_purchase_order_line_variant_tenant
    FOREIGN KEY (tenant_id, variant_id) REFERENCES product_variants(tenant_id, id)
    ON DELETE RESTRICT;
CREATE INDEX ix_purchase_order_lines_variant
    ON purchase_order_lines(tenant_id, product_id, variant_id);

