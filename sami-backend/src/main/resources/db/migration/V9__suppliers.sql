CREATE SEQUENCE sup_code_seq START WITH 1001;

CREATE TABLE suppliers (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    supplier_code       VARCHAR(32)   NOT NULL,
    company_name        VARCHAR(160)  NOT NULL,
    display_name        VARCHAR(160)  NOT NULL,
    legal_name          VARCHAR(160),
    national_id         VARCHAR(32),
    economic_code       VARCHAR(32),
    tax_number          VARCHAR(64),
    registration_number VARCHAR(64),
    owner_name          VARCHAR(120),
    website             VARCHAR(255),
    country             VARCHAR(100),
    province            VARCHAR(100),
    city                VARCHAR(100),
    postal_code         VARCHAR(20),
    description         VARCHAR(2000),
    type_id             BIGINT        NOT NULL,
    status_id           BIGINT        NOT NULL,
    payment_term_id     BIGINT,
    credit_limit        NUMERIC(14,2),
    rating_avg          NUMERIC(4,2),
    source_customer_id  BIGINT,       -- provenance for records migrated from CRM
    archived_at         TIMESTAMPTZ,
    archived_by         BIGINT,
    deleted_at          TIMESTAMPTZ,
    deleted_by          BIGINT,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version             BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT pk_suppliers PRIMARY KEY (id),
    CONSTRAINT uq_suppliers_code UNIQUE (supplier_code),
    CONSTRAINT fk_suppliers_type   FOREIGN KEY (type_id)   REFERENCES sup_types (id),
    CONSTRAINT fk_suppliers_status FOREIGN KEY (status_id) REFERENCES sup_statuses (id),
    CONSTRAINT fk_suppliers_payment_term FOREIGN KEY (payment_term_id)
        REFERENCES sup_payment_terms (id)
);
CREATE INDEX idx_suppliers_status ON suppliers (status_id);
CREATE INDEX idx_suppliers_type   ON suppliers (type_id);
CREATE INDEX idx_suppliers_name   ON suppliers (lower(company_name));
CREATE INDEX idx_suppliers_city   ON suppliers (lower(city));
CREATE INDEX idx_suppliers_tax    ON suppliers (tax_number);
CREATE INDEX idx_suppliers_rating ON suppliers (rating_avg);

-- Supplier-level phones and emails.
