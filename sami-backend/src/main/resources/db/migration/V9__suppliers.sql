-- ---------------------------------------------------------------------------
-- Purchasing now references the supplier registry. Any CRM records already
-- used as purchase suppliers become supplier rows (provenance kept), then the
-- foreign key is repointed.
INSERT INTO suppliers (supplier_code, company_name, display_name, national_id, tax_number,
                       type_id, status_id, source_customer_id)
SELECT 'SUP-' || lpad(nextval('sup_code_seq')::text, 6, '0'),
       COALESCE(c.company_name, c.display_name),
       c.display_name,
       c.national_code,
       c.tax_number,
       (SELECT id FROM sup_types WHERE is_default),
       (SELECT id FROM sup_statuses WHERE is_default),
       c.id
FROM customers c
WHERE c.id IN (SELECT DISTINCT supplier_id FROM purchases);

ALTER TABLE purchases DROP CONSTRAINT fk_purchases_supplier;
UPDATE purchases p SET supplier_id = s.id
FROM suppliers s WHERE s.source_customer_id = p.supplier_id;
ALTER TABLE purchases ADD CONSTRAINT fk_purchases_supplier
    FOREIGN KEY (supplier_id) REFERENCES suppliers (id);

