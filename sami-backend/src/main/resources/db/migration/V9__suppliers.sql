-- Supplier Management: configurable types/statuses/categories/tags/payment
-- terms/rating criteria/document types/duplicate rules, supplier registry with
-- channels, addresses, contact persons, bank accounts, ratings, documents and
-- an append-only log. Also repoints purchasing at this registry.

CREATE TABLE sup_types (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code          VARCHAR(64)  NOT NULL,
    name          VARCHAR(100) NOT NULL,
    description   VARCHAR(255),
    is_default    BOOLEAN      NOT NULL DEFAULT FALSE,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    is_system     BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order INTEGER      NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_sup_types PRIMARY KEY (id),
    CONSTRAINT uq_sup_types_code UNIQUE (code)
);
CREATE UNIQUE INDEX uq_sup_types_default ON sup_types (is_default) WHERE is_default;

