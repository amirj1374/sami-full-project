-- KPI definitions. calculation_method / aggregation are technical strategy
-- selectors (validated against the code enums); formula is provider-specific.
CREATE TABLE kpi_definitions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code               VARCHAR(64)   NOT NULL,
    name               VARCHAR(150)  NOT NULL,
    description        VARCHAR(500),
    calculation_method VARCHAR(32)   NOT NULL DEFAULT 'PROVIDER',
    formula            VARCHAR(1000),
    aggregation        VARCHAR(16)   NOT NULL DEFAULT 'LAST',
    data_source_id     BIGINT,
    refresh_policy_id  BIGINT,
    target_value       NUMERIC(18,4),
    unit               VARCHAR(32),
    status_id          BIGINT        NOT NULL,
    owner_id           BIGINT,
    created_by         BIGINT,
    created_by_email   VARCHAR(255),
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT pk_kpi_definitions PRIMARY KEY (id),
    CONSTRAINT uq_kpi_definitions_code UNIQUE (code),
    CONSTRAINT fk_kpi_status      FOREIGN KEY (status_id)         REFERENCES dash_kpi_statuses (id),
    CONSTRAINT fk_kpi_datasource  FOREIGN KEY (data_source_id)    REFERENCES dash_data_sources (id),
    CONSTRAINT fk_kpi_refresh     FOREIGN KEY (refresh_policy_id) REFERENCES dash_refresh_policies (id),
    CONSTRAINT fk_kpi_owner       FOREIGN KEY (owner_id)          REFERENCES users (id)
);
CREATE INDEX idx_kpi_status ON kpi_definitions (status_id);

-- Configurable threshold levels per KPI (Excellent/Good/Warning/Critical/...).
CREATE TABLE kpi_thresholds (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    kpi_id     BIGINT        NOT NULL,
    level_name VARCHAR(64)   NOT NULL,
    color      VARCHAR(32),
    min_value  NUMERIC(18,4),
    max_value  NUMERIC(18,4),
    sort_order INTEGER       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version    BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT pk_kpi_thresholds PRIMARY KEY (id),
    CONSTRAINT fk_kpi_thresholds_kpi FOREIGN KEY (kpi_id) REFERENCES kpi_definitions (id) ON DELETE CASCADE
);
CREATE INDEX idx_kpi_thresholds_kpi ON kpi_thresholds (kpi_id);

-- Historical KPI calculation store (supports trend analysis & recalculation).
CREATE TABLE kpi_values (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    kpi_id          BIGINT        NOT NULL,
    value           NUMERIC(18,4) NOT NULL,
    period_key      VARCHAR(32)   NOT NULL DEFAULT 'ALL',
    threshold_level VARCHAR(64),
    computed_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT pk_kpi_values PRIMARY KEY (id),
    CONSTRAINT fk_kpi_values_kpi FOREIGN KEY (kpi_id) REFERENCES kpi_definitions (id) ON DELETE CASCADE
);
CREATE INDEX idx_kpi_values_kpi ON kpi_values (kpi_id, computed_at DESC);
CREATE UNIQUE INDEX uq_kpi_values_period ON kpi_values (kpi_id, period_key, computed_at);

-- Dashboards. owner_id is null for system/executive dashboards; role_id targets
-- a role-based dashboard; company_id/branch_id are forward-compat (multi-tenant).
CREATE TABLE dashboards (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code             VARCHAR(64)  NOT NULL,
    name             VARCHAR(150) NOT NULL,
    description      VARCHAR(500),
    owner_id         BIGINT,
    role_id          BIGINT,
    status_id        BIGINT       NOT NULL,
    visibility_id    BIGINT       NOT NULL,
    is_default       BOOLEAN      NOT NULL DEFAULT FALSE,
    company_id       BIGINT,
    branch_id        BIGINT,
    created_by       BIGINT,
    created_by_email VARCHAR(255),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_dashboards PRIMARY KEY (id),
    CONSTRAINT uq_dashboards_code UNIQUE (code),
    CONSTRAINT fk_dashboards_status     FOREIGN KEY (status_id)     REFERENCES dash_statuses (id),
    CONSTRAINT fk_dashboards_visibility FOREIGN KEY (visibility_id) REFERENCES dash_visibilities (id),
    CONSTRAINT fk_dashboards_owner      FOREIGN KEY (owner_id)      REFERENCES users (id),
    CONSTRAINT fk_dashboards_role       FOREIGN KEY (role_id)       REFERENCES roles (id)
);
CREATE INDEX idx_dashboards_owner ON dashboards (owner_id);
CREATE INDEX idx_dashboards_role  ON dashboards (role_id);

CREATE TABLE dashboard_widgets (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    dashboard_id        BIGINT       NOT NULL,
    code                VARCHAR(64)  NOT NULL,
    widget_type_id      BIGINT       NOT NULL,
    chart_type_id       BIGINT,
    kpi_id              BIGINT,
    title               VARCHAR(150) NOT NULL,
    description         VARCHAR(500),
    data_source_id      BIGINT,
    refresh_policy_id   BIGINT,
    position_x          INTEGER      NOT NULL DEFAULT 0,
    position_y          INTEGER      NOT NULL DEFAULT 0,
    width               INTEGER      NOT NULL DEFAULT 3,
    height              INTEGER      NOT NULL DEFAULT 2,
    required_permission VARCHAR(100),
    config              JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_dashboard_widgets PRIMARY KEY (id),
    CONSTRAINT uq_dashboard_widgets_code UNIQUE (dashboard_id, code),
    CONSTRAINT fk_dw_dashboard   FOREIGN KEY (dashboard_id)      REFERENCES dashboards (id) ON DELETE CASCADE,
    CONSTRAINT fk_dw_type        FOREIGN KEY (widget_type_id)    REFERENCES dash_widget_types (id),
    CONSTRAINT fk_dw_chart_type  FOREIGN KEY (chart_type_id)     REFERENCES dash_chart_types (id),
    CONSTRAINT fk_dw_kpi         FOREIGN KEY (kpi_id)            REFERENCES kpi_definitions (id),
    CONSTRAINT fk_dw_datasource  FOREIGN KEY (data_source_id)    REFERENCES dash_data_sources (id),
    CONSTRAINT fk_dw_refresh     FOREIGN KEY (refresh_policy_id) REFERENCES dash_refresh_policies (id),
    CONSTRAINT ck_dw_size CHECK (width > 0 AND height > 0)
);
CREATE INDEX idx_dw_dashboard ON dashboard_widgets (dashboard_id);

-- Sharing: a dashboard can be shared with users or roles, optionally editable.
CREATE TABLE dashboard_shares (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    dashboard_id   BIGINT      NOT NULL,
    target_type    VARCHAR(16) NOT NULL,   -- USER | ROLE
    target_user_id BIGINT,
    target_role_id BIGINT,
    can_edit       BOOLEAN     NOT NULL DEFAULT FALSE,
    created_by     BIGINT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_dashboard_shares PRIMARY KEY (id),
    CONSTRAINT fk_ds_dashboard FOREIGN KEY (dashboard_id)   REFERENCES dashboards (id) ON DELETE CASCADE,
    CONSTRAINT fk_ds_user      FOREIGN KEY (target_user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_ds_role      FOREIGN KEY (target_role_id) REFERENCES roles (id) ON DELETE CASCADE,
    CONSTRAINT ck_ds_target CHECK (
        (target_type = 'USER' AND target_user_id IS NOT NULL) OR
        (target_type = 'ROLE' AND target_role_id IS NOT NULL))
);
CREATE INDEX idx_ds_dashboard ON dashboard_shares (dashboard_id);
CREATE INDEX idx_ds_user      ON dashboard_shares (target_user_id);
CREATE INDEX idx_ds_role      ON dashboard_shares (target_role_id);

