-- Dashboard, KPI & Executive Cockpit — a generic, configuration-driven
-- visualization engine. Business data arrives through ReportingProvider beans
-- (SPI); this module contains no per-domain dashboard logic. Widget types,
-- chart types, data sources, refresh policies, statuses and visibilities are all
-- configurable rows, so new kinds never require code changes.

-- Dashboard lifecycle statuses (Draft/Active/Inactive/Archived seeded).
CREATE TABLE dash_statuses (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code              VARCHAR(64)  NOT NULL,
    name              VARCHAR(100) NOT NULL,
    is_default        BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active_state   BOOLEAN      NOT NULL DEFAULT FALSE,
    is_archived_state BOOLEAN      NOT NULL DEFAULT FALSE,
    is_system         BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order     INTEGER      NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_dash_statuses PRIMARY KEY (id),
    CONSTRAINT uq_dash_statuses_code UNIQUE (code)
);
CREATE UNIQUE INDEX uq_dash_statuses_default  ON dash_statuses (is_default)        WHERE is_default;
CREATE UNIQUE INDEX uq_dash_statuses_archived ON dash_statuses (is_archived_state) WHERE is_archived_state;

