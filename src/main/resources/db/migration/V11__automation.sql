FROM modules m
CROSS JOIN (VALUES
    ('view',          'View'),
    ('create',        'Create'),
    ('edit',          'Edit'),
    ('delete',        'Delete'),
    ('execute',       'Execute'),
    ('manage-status', 'Manage status'),
    ('manage-config', 'Manage configuration')
) AS a(action, label)
WHERE m.code = 'automation';
