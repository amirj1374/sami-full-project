-- Which ERP entities accept custom fields. A business module "registers its
-- requirement" by inserting a row (or shipping one in its own migration).
CREATE TABLE meta_entities (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    module_code   VARCHAR(64)  NOT NULL,
    entity_code   VARCHAR(64)  NOT NULL,
    label         VARCHAR(160) NOT NULL,
    description   VARCHAR(1000),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    is_system     BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order INTEGER      NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_meta_entities PRIMARY KEY (id),
    CONSTRAINT uq_meta_entities_target UNIQUE (module_code, entity_code)
);

