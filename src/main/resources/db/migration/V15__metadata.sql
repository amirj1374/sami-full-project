-- Dynamic Forms & Custom Metadata — extend the ERP without a software update.
-- Business modules never implement a metadata engine: they register the entities
-- they allow to be extended, and this module owns field definitions, typed
-- value storage (searchable/sortable/reportable), versioned forms and
-- role/company/branch/device/stage-aware layouts.
--
-- Storage decision: values live in a TYPED EAV table rather than one JSONB blob,
-- because the spec requires custom fields to be searchable, filterable, sortable
-- and reportable — that needs real indexable columns per storage kind.

-- Configurable field-type catalogue. `handler_key` resolves to a
-- FieldTypeHandler bean; `storage_kind` decides which value column is used.
CREATE TABLE meta_field_types (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code            VARCHAR(64)  NOT NULL,
    name            VARCHAR(100) NOT NULL,
    handler_key     VARCHAR(64)  NOT NULL,
    storage_kind    VARCHAR(16)  NOT NULL,   -- TEXT | NUMBER | BOOLEAN | DATE | JSON
    supports_options BOOLEAN     NOT NULL DEFAULT FALSE,
    is_reference    BOOLEAN      NOT NULL DEFAULT FALSE,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    is_system       BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order   INTEGER      NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_meta_field_types PRIMARY KEY (id),
    CONSTRAINT uq_meta_field_types_code UNIQUE (code),
    CONSTRAINT ck_meta_field_types_storage CHECK (storage_kind IN ('TEXT','NUMBER','BOOLEAN','DATE','JSON'))
);

