-- =====================================================================
-- V21 — Customer Portal & Self-Service (module 14)
--
-- Secure customer-facing access to their own data.
--
-- THE CENTRAL RULE: this module owns NO business data. It owns portal
-- accounts, sessions, requests, messages and audit. Everything a customer
-- sees about installments, repairs, warranties, invoices or trade-ins is
-- fetched at read time from the owning module through the
-- PortalDataProvider SPI. Dashboard widgets are rows whose provider_key
-- resolves a bean; a widget with no registered provider is reported as
-- unavailable rather than silently empty.
--
-- SECURITY MODEL. A portal account is NOT a staff `users` row. Customers
-- authenticate in a separate realm with their own principal, their own
-- sessions table and their own token audience, so a portal token can never
-- satisfy a staff endpoint and a customer can never hold an RBAC role.
-- Customer-facing capabilities are configured in portal_capabilities,
-- deliberately disjoint from the staff `permissions` table.
--
-- Account lockout lives here (failed_attempts / locked_until) because it is
-- portal-account lifecycle state, not shared infrastructure — this is the
-- first internet-facing login surface in the system.
-- =====================================================================


