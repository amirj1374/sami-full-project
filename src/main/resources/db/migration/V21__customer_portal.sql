-- ---------------------------------------------------------------------
-- Authentication methods. handler_key resolves a PortalAuthMethod bean.
--
-- `requires_delivery` marks methods that must send a code somewhere. Such a
-- method is refused at runtime unless an OtpDeliveryChannel bean is
-- registered — the portal will not issue a code it can only write to a log.
-- ---------------------------------------------------------------------
CREATE TABLE portal_auth_methods (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code              VARCHAR(64)  NOT NULL,
    name              VARCHAR(100) NOT NULL,
    handler_key       VARCHAR(64)  NOT NULL,
    config            JSONB        NOT NULL DEFAULT '{}'::jsonb,
    enabled           BOOLEAN      NOT NULL DEFAULT FALSE,
    is_primary_method BOOLEAN      NOT NULL DEFAULT FALSE,
    requires_delivery BOOLEAN      NOT NULL DEFAULT FALSE,
    is_second_factor  BOOLEAN      NOT NULL DEFAULT FALSE,
    is_system         BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order     INTEGER      NOT NULL DEFAULT 0,
    tenant_id         BIGINT,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_portal_auth_methods PRIMARY KEY (id),
    CONSTRAINT fk_portal_auth_methods_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX uq_portal_auth_methods_code_global ON portal_auth_methods (code) WHERE tenant_id IS NULL;
CREATE UNIQUE INDEX uq_portal_auth_methods_code_tenant ON portal_auth_methods (tenant_id, code) WHERE tenant_id IS NOT NULL;

