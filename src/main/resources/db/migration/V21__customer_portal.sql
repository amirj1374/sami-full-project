    CONSTRAINT fk_portal_requests_type    FOREIGN KEY (type_id) REFERENCES portal_request_types (id),
    CONSTRAINT fk_portal_requests_status  FOREIGN KEY (status_id) REFERENCES portal_request_statuses (id),
    CONSTRAINT fk_portal_requests_tenant  FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE RESTRICT
);
CREATE INDEX idx_portal_requests_account ON portal_requests (account_id, created_at DESC);
CREATE INDEX idx_portal_requests_status  ON portal_requests (tenant_id, status_id);

-- Threaded messages on a request, and standalone secure conversations.
-- `is_internal` keeps staff-only notes out of the customer's view.
CREATE TABLE portal_messages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    request_id   BIGINT,
    account_id   BIGINT       NOT NULL,
    parent_id    BIGINT,
    author_kind  VARCHAR(16)  NOT NULL,
    author_id    BIGINT,
    author_name  VARCHAR(160),
    subject      VARCHAR(255),
    body         TEXT         NOT NULL,
    is_internal  BOOLEAN      NOT NULL DEFAULT FALSE,
    read_at      TIMESTAMPTZ,
    tenant_id    BIGINT       NOT NULL DEFAULT tenancy_default_tenant_id(),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_portal_messages PRIMARY KEY (id),
    CONSTRAINT ck_portal_messages_author CHECK (author_kind IN ('CUSTOMER', 'STAFF', 'SYSTEM')),
    -- Only staff may write internal notes.
    CONSTRAINT ck_portal_messages_internal CHECK (NOT is_internal OR author_kind <> 'CUSTOMER'),
    CONSTRAINT fk_portal_messages_request FOREIGN KEY (request_id) REFERENCES portal_requests (id) ON DELETE CASCADE,
    CONSTRAINT fk_portal_messages_account FOREIGN KEY (account_id) REFERENCES portal_accounts (id) ON DELETE CASCADE,
    CONSTRAINT fk_portal_messages_parent  FOREIGN KEY (parent_id) REFERENCES portal_messages (id) ON DELETE CASCADE,
    CONSTRAINT fk_portal_messages_tenant  FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE RESTRICT
);
CREATE INDEX idx_portal_messages_account ON portal_messages (account_id, created_at DESC);
CREATE INDEX idx_portal_messages_request ON portal_messages (request_id);

-- Attachments reference the files module by UUID. No bytes here.
CREATE TABLE portal_attachments (
