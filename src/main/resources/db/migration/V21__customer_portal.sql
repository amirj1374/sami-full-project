    tenant_id   BIGINT       NOT NULL DEFAULT tenancy_default_tenant_id(),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_portal_attachments PRIMARY KEY (id),
    CONSTRAINT ck_portal_attachments_parent CHECK (request_id IS NOT NULL OR message_id IS NOT NULL),
    CONSTRAINT fk_portal_attach_request FOREIGN KEY (request_id) REFERENCES portal_requests (id) ON DELETE CASCADE,
