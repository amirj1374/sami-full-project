    registered_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    verified_at           TIMESTAMPTZ,
    last_login_at         TIMESTAMPTZ,
    last_login_ip         VARCHAR(64),
    -- Lockout is portal-account lifecycle state; this is the first
    -- internet-facing login surface in the system.
    failed_attempts       INTEGER      NOT NULL DEFAULT 0,
    locked_until          TIMESTAMPTZ,
    must_change_password  BOOLEAN      NOT NULL DEFAULT FALSE,
    marketing_opt_in      BOOLEAN      NOT NULL DEFAULT FALSE,
    invited_by            BIGINT,
    tenant_id             BIGINT       NOT NULL DEFAULT tenancy_default_tenant_id(),
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version               BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_portal_accounts PRIMARY KEY (id),
    CONSTRAINT uq_portal_accounts_username UNIQUE (tenant_id, username),
    -- One portal account per customer: two accounts for one customer would
    -- make "own data only" ambiguous.
    CONSTRAINT uq_portal_accounts_customer UNIQUE (tenant_id, customer_id),
    CONSTRAINT fk_portal_accounts_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT,
    CONSTRAINT fk_portal_accounts_status   FOREIGN KEY (status_id) REFERENCES portal_account_statuses (id),
    CONSTRAINT fk_portal_accounts_tenant   FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE RESTRICT
);
