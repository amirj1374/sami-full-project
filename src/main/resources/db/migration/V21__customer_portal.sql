    CONSTRAINT fk_portal_attach_tenant  FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE RESTRICT
);

-- Explicit grant of a managed file to a customer.
--
-- This is the ONLY way a portal account may read a file: the portal never
-- infers access from a file's contents or its owning module. Revocable, and
-- every download is audited.
CREATE TABLE portal_document_grants (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id    BIGINT       NOT NULL,
    file_uuid     UUID         NOT NULL,
    title         VARCHAR(255),
    source_module VARCHAR(64),
    source_entity VARCHAR(64),
    source_record_id BIGINT,
    granted_by    BIGINT,
    granted_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    revoked_at    TIMESTAMPTZ,
    download_count INTEGER     NOT NULL DEFAULT 0,
    last_downloaded_at TIMESTAMPTZ,
    requires_signature BOOLEAN NOT NULL DEFAULT FALSE,
    signed_at     TIMESTAMPTZ,
    signature_ref VARCHAR(255),
    tenant_id     BIGINT       NOT NULL DEFAULT tenancy_default_tenant_id(),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_portal_document_grants PRIMARY KEY (id),
    CONSTRAINT uq_portal_document_grants UNIQUE (account_id, file_uuid),
    CONSTRAINT fk_portal_grants_account FOREIGN KEY (account_id) REFERENCES portal_accounts (id) ON DELETE CASCADE,
    CONSTRAINT fk_portal_grants_tenant  FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE RESTRICT
);
CREATE INDEX idx_portal_grants_account ON portal_document_grants (account_id, revoked_at);

