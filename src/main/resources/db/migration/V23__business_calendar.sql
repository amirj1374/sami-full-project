-- =====================================================================
-- Post-migration assertions
-- =====================================================================

DO $$
DECLARE
    cal_id  BIGINT;
    dow_cnt BIGINT;
    sys_cnt BIGINT;
BEGIN
    SELECT id INTO cal_id FROM business_calendars WHERE code = 'DEFAULT';
    IF cal_id IS NULL THEN
        RAISE EXCEPTION 'V23: default business calendar was not created';
    END IF;

    SELECT count(*) INTO dow_cnt FROM calendar_working_days WHERE calendar_id = cal_id;
    IF dow_cnt <> 7 THEN
        RAISE EXCEPTION 'V23: expected 7 weekday rows for the default calendar, found %', dow_cnt;
    END IF;

    SELECT count(*) INTO sys_cnt FROM calendar_systems WHERE is_default;
    IF sys_cnt <> 1 THEN
        RAISE EXCEPTION 'V23: expected exactly 1 default calendar system, found %', sys_cnt;
    END IF;
END $$;
