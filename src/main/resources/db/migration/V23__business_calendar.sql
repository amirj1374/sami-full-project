-- Default calendar for the seeded company: Iranian working week.
INSERT INTO business_calendars (code, name, description, company_id, calendar_system_id,
                                timezone, slot_minutes, is_default, is_active, display_order)
SELECT 'DEFAULT', 'Default Business Calendar', 'Saturday–Thursday trading, Friday weekend',
       c.id, cs.id, 'Asia/Tehran', 30, TRUE, TRUE, 10
FROM companies c CROSS JOIN calendar_systems cs
WHERE c.code = 'DEFAULT' AND cs.code = 'PERSIAN';

-- ISO weekdays: 1 Mon, 2 Tue, 3 Wed, 4 Thu, 5 Fri, 6 Sat, 7 Sun.
-- Friday (5) is the Iranian weekend; every other day trades.
INSERT INTO calendar_working_days (calendar_id, day_of_week, is_working_day)
SELECT bc.id, d.dow, d.working
FROM business_calendars bc
CROSS JOIN (VALUES (1, TRUE), (2, TRUE), (3, TRUE), (4, TRUE),
                   (5, FALSE), (6, TRUE), (7, TRUE)) AS d(dow, working)
WHERE bc.code = 'DEFAULT';

INSERT INTO calendar_shifts (calendar_id, code, name, day_of_week, start_time, end_time,
                             max_concurrent, is_overtime, is_bookable, is_active, display_order)
SELECT bc.id, s.code, s.name, s.dow, s.st, s.et, 0, FALSE, TRUE, TRUE, s.ord
FROM business_calendars bc
CROSS JOIN (VALUES
    ('MORNING',   'Morning',        NULL::SMALLINT, TIME '09:00', TIME '13:00', 10),
    ('AFTERNOON', 'Afternoon',      NULL::SMALLINT, TIME '16:00', TIME '20:00', 20),
    ('THU_SHORT', 'Thursday Short', 4::SMALLINT,    TIME '09:00', TIME '13:00', 30)
) AS s(code, name, dow, st, et, ord)
WHERE bc.code = 'DEFAULT';

-- Recurring Persian national holidays. Dates are Farvardin/Khordad in the
-- Solar Hijri calendar and resolve to a different Gregorian day each year.
INSERT INTO holidays (calendar_id, holiday_type_id, name, is_recurring,
                      recurrence_system_id, recurrence_month, recurrence_day, duration_days)
SELECT NULL, ht.id, h.name, TRUE, cs.id, h.mon, h.day, h.dur
FROM holiday_types ht
CROSS JOIN calendar_systems cs
CROSS JOIN (VALUES
    ('Nowruz',                       1, 1,  4),
    ('Islamic Republic Day',         1, 12, 1),
    ('Sizdah Bedar (Nature Day)',    1, 13, 1),
    ('Death of Imam Khomeini',       3, 14, 1),
    ('Khordad National Uprising',    3, 15, 1)
) AS h(name, mon, day, dur)
WHERE ht.code = 'NATIONAL' AND cs.code = 'PERSIAN';


