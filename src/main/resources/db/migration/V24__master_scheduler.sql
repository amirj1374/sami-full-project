-- ---------------------------------------------------------------------
-- What kind of appointment this is, and the rules that follow from it.
--
-- `subject_provider_key` binds the type to a ScheduleSubjectProvider SPI
-- bean: 'repair' resolves a repair order, 'trade_in' a valuation. A type
-- whose provider has no bean still books — it simply carries no linked
-- business record. That is what lets repair appointments be configured
-- today and become live the day a repair module ships, with no migration.
-- ---------------------------------------------------------------------
CREATE TABLE appointment_types (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code                    VARCHAR(64)  NOT NULL,
    name                    VARCHAR(100) NOT NULL,
    description             VARCHAR(500),
    category_id             BIGINT,

    -- Timing. Buffers are reserved on the resource but are not customer
    -- time, which is why they are separate from duration.
    default_duration_minutes INTEGER     NOT NULL DEFAULT 30,
    min_duration_minutes     INTEGER     NOT NULL DEFAULT 15,
    max_duration_minutes     INTEGER     NOT NULL DEFAULT 480,
    preparation_minutes      INTEGER     NOT NULL DEFAULT 0,
    cleanup_minutes          INTEGER     NOT NULL DEFAULT 0,
    buffer_before_minutes    INTEGER     NOT NULL DEFAULT 0,
    buffer_after_minutes     INTEGER     NOT NULL DEFAULT 0,

    -- Booking rules.
    requires_customer        BOOLEAN     NOT NULL DEFAULT FALSE,
    requires_supplier        BOOLEAN     NOT NULL DEFAULT FALSE,
    requires_resource        BOOLEAN     NOT NULL DEFAULT TRUE,
    requires_approval        BOOLEAN     NOT NULL DEFAULT FALSE,
    allows_waiting_list      BOOLEAN     NOT NULL DEFAULT TRUE,
    allows_self_service      BOOLEAN     NOT NULL DEFAULT FALSE,
    allows_overbooking       BOOLEAN     NOT NULL DEFAULT FALSE,
    enforce_working_hours    BOOLEAN     NOT NULL DEFAULT TRUE,

    -- How far ahead bookings open, and how late they may be made/cancelled.
    max_advance_days         INTEGER     NOT NULL DEFAULT 90,
    min_notice_minutes       INTEGER     NOT NULL DEFAULT 0,
    cancellation_notice_minutes INTEGER  NOT NULL DEFAULT 0,

    -- Minutes after start_time before an arrival counts as late; and after
    -- which an unarrived appointment may be auto-marked no-show.
    late_threshold_minutes   INTEGER     NOT NULL DEFAULT 15,
    no_show_threshold_minutes INTEGER    NOT NULL DEFAULT 30,

    subject_provider_key     VARCHAR(64),
    module_code              VARCHAR(64),
    color                    VARCHAR(16),

    is_default               BOOLEAN     NOT NULL DEFAULT FALSE,
    is_system                BOOLEAN     NOT NULL DEFAULT FALSE,
    is_active                BOOLEAN     NOT NULL DEFAULT TRUE,
    display_order            INTEGER     NOT NULL DEFAULT 0,

