-- =====================================================================
-- V24 — Enterprise Master Scheduler, Resource Reservation & Appointment
--       Management
--
-- Centralised scheduling of appointments, reservations and shared
-- resources. This is NOT the background job scheduler (V19, which runs
-- @Scheduled work) and NOT the business calendar (V23, which defines when
-- the business is open). This module books business activities INTO the
-- time V23 declares available.
--
-- ---------------------------------------------------------------------
-- THE CENTRAL DESIGN DECISION: double booking is prevented by the
-- database, not by service code.
--
-- The spec's "concurrent reservation requests" edge case cannot be solved
-- with a SELECT-then-INSERT availability check at any isolation level
-- below SERIALIZABLE: two transactions both read "free", both write, and
-- the technician is double-booked. Application-level locking would need a
-- lock per resource held across the whole booking transaction.
--
-- Instead `reservations` carries a GiST exclusion constraint over
-- (resource_id, [starts_at, ends_at)). Postgres rejects the second
-- overlapping insert outright, whatever the interleaving, and the service
-- translates that violation into a domain conflict. Correctness does not
-- depend on any caller remembering to check first.
--
-- The constraint is predicated on `holds_resource`, so cancelled and
-- no-show reservations stop occupying the slot without being deleted —
-- history is preserved, which "Reservation History" requires.
-- ---------------------------------------------------------------------
--
-- Behaviour is data throughout: statuses, appointment types, resource
-- categories, conflict policies and reminder channels are configuration
-- rows with behavioural flags. Adding "Video Consultation" is an INSERT.
-- =====================================================================

-- Required for an exclusion constraint mixing equality on a scalar with
-- range overlap; plain GiST cannot index bigint equality on its own.
CREATE EXTENSION IF NOT EXISTS btree_gist;


