-- ---------------------------------------------------------------------
-- Reservations: a resource occupied for a span.
--
-- A schedule normally produces one reservation per required resource
-- (technician + repair bench). `schedule_id` is nullable so a resource can
-- also be blocked WITHOUT an appointment — maintenance, annual leave, a
-- room held for a private event — which the "resource goes out of service"
-- edge case needs.
--
-- `starts_at`/`ends_at` here include the appointment type's preparation,
-- cleanup and buffer minutes. That is why they are stored separately from
-- the schedule's own window rather than being derived: the resource is
-- genuinely busy longer than the customer is present, and the overlap
-- check must use the longer span.
-- ---------------------------------------------------------------------
CREATE TABLE reservations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_number  VARCHAR(32)  NOT NULL,
    schedule_id         BIGINT,
    resource_id         BIGINT       NOT NULL,
    status_id           BIGINT       NOT NULL,

    starts_at           TIMESTAMPTZ  NOT NULL,
    ends_at             TIMESTAMPTZ  NOT NULL,
    duration_minutes    INTEGER      GENERATED ALWAYS AS
                            ((EXTRACT(EPOCH FROM (ends_at - starts_at)) / 60)::INTEGER) STORED,

    -- Denormalised from the status so the exclusion constraint has an
    -- immutable column to predicate on. Kept in step by ReservationService
    -- whenever the status changes; the assertion at the end of this
    -- migration and a unit test both guard the invariant.
    holds_resource      BOOLEAN      NOT NULL DEFAULT TRUE,

    purpose             VARCHAR(500),
    priority            INTEGER      NOT NULL DEFAULT 0,
    is_maintenance      BOOLEAN      NOT NULL DEFAULT FALSE,

    customer_id         BIGINT,
    supplier_id         BIGINT,
    employee_user_id    BIGINT,

    released_at         TIMESTAMPTZ,
    release_reason      VARCHAR(500),

    created_by          BIGINT,
    tenant_id           BIGINT       NOT NULL DEFAULT tenancy_default_tenant_id(),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version             BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT pk_reservations PRIMARY KEY (id),
    CONSTRAINT fk_reservations_schedule FOREIGN KEY (schedule_id) REFERENCES schedules (id) ON DELETE CASCADE,
    CONSTRAINT fk_reservations_resource FOREIGN KEY (resource_id) REFERENCES resources (id) ON DELETE CASCADE,
    CONSTRAINT fk_reservations_status FOREIGN KEY (status_id) REFERENCES schedule_statuses (id),
    CONSTRAINT fk_reservations_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE SET NULL,
    CONSTRAINT fk_reservations_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE SET NULL,
    CONSTRAINT fk_reservations_employee FOREIGN KEY (employee_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_reservations_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT ck_reservations_window CHECK (ends_at > starts_at)
);
CREATE UNIQUE INDEX uq_reservations_number ON reservations (tenant_id, reservation_number);
CREATE INDEX ix_reservations_resource_window ON reservations (resource_id, starts_at, ends_at);
CREATE INDEX ix_reservations_schedule ON reservations (schedule_id) WHERE schedule_id IS NOT NULL;
CREATE INDEX ix_reservations_tenant ON reservations (tenant_id);

-- -------------------------------------------------------------------
-- THE constraint. Two live reservations may never overlap on the same
-- resource. '[)' makes the range half-open so a 10:00–11:00 booking and
-- an 11:00–12:00 booking do NOT collide — back-to-back appointments are
-- the normal case and must remain legal.
--
-- Released, cancelled and no-show rows set holds_resource = FALSE and
-- drop out of the constraint while staying in the table for history.
-- -------------------------------------------------------------------
ALTER TABLE reservations ADD CONSTRAINT ex_reservations_no_double_booking
    EXCLUDE USING gist (
        resource_id WITH =,
        tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (holds_resource);


-- ---------------------------------------------------------------------
-- Waiting list. An entry is a standing request for a slot that was not
-- free; promotion turns it into a real schedule.
-- ---------------------------------------------------------------------
CREATE TABLE waiting_list_entries (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    entry_number        VARCHAR(32)  NOT NULL,
    appointment_type_id BIGINT       NOT NULL,

    customer_id         BIGINT,
    supplier_id         BIGINT,
    branch_id           BIGINT,
    -- Optional: the specific resource asked for. NULL means any suitable.
    resource_id         BIGINT,

    -- The window the requester will accept.
    desired_from        TIMESTAMPTZ  NOT NULL,
    desired_to          TIMESTAMPTZ  NOT NULL,
    duration_minutes    INTEGER      NOT NULL,

