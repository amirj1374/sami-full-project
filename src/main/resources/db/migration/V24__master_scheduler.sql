-- =====================================================================
-- Post-migration assertions
--
-- The exclusion constraint is the module's core guarantee, so it is
-- proved here rather than assumed: if a future migration or a manual
-- edit ever drops it, this fails loudly on the next fresh deploy.
-- =====================================================================

DO $$
DECLARE
    has_exclusion BOOLEAN;
    default_status_count BIGINT;
    type_count BIGINT;
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ex_reservations_no_double_booking' AND contype = 'x'
    ) INTO has_exclusion;
    IF NOT has_exclusion THEN
        RAISE EXCEPTION 'V24: the double-booking exclusion constraint is missing';
    END IF;

    SELECT count(*) INTO default_status_count FROM schedule_statuses WHERE is_default;
    IF default_status_count <> 1 THEN
        RAISE EXCEPTION 'V24: expected exactly 1 default schedule status, found %', default_status_count;
    END IF;

    SELECT count(*) INTO type_count FROM appointment_types WHERE is_active;
    IF type_count < 1 THEN
        RAISE EXCEPTION 'V24: no appointment types were seeded';
    END IF;

    -- A terminal status must never hold a resource, or cancelled bookings
    -- would keep blocking the slot they were cancelled from.
    IF EXISTS (SELECT 1 FROM schedule_statuses WHERE is_terminal AND blocks_resource) THEN
        RAISE EXCEPTION 'V24: a terminal status is flagged as blocking its resource';
    END IF;
END $$;
