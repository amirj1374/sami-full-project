    CONSTRAINT ck_appointment_types_duration CHECK (
        default_duration_minutes > 0
        AND min_duration_minutes > 0
        AND max_duration_minutes >= min_duration_minutes
        AND default_duration_minutes BETWEEN min_duration_minutes AND max_duration_minutes),
    CONSTRAINT ck_appointment_types_buffers CHECK (
        preparation_minutes >= 0 AND cleanup_minutes >= 0
