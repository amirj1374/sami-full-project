-- ---------------------------------------------------------------------
-- Lifecycle columns on modules.
--
-- Added nullable, backfilled, then constrained — the standard safe
-- sequence, and the one V16 used for tenant_id. Nothing about an existing
-- row changes meaning: `enabled` still controls menu visibility and
-- `is_system` still protects the admin modules.
-- ---------------------------------------------------------------------
ALTER TABLE modules
    ADD COLUMN backend_status_id   BIGINT,
    ADD COLUMN frontend_status_id  BIGINT,
    -- NULL means "derive from the two axes"; a value pins it explicitly.
    ADD COLUMN overall_status_id   BIGINT,
    ADD COLUMN release_version     VARCHAR(32),
    ADD COLUMN progress_percentage SMALLINT     NOT NULL DEFAULT 0,
    ADD COLUMN development_notes   VARCHAR(2000),
    -- Distinct from `enabled`: an administrator disables a module, whereas
    -- availability reflects whether it is fit to be used at all in this
    -- deployment. Keeping them apart means turning a module off for one
    -- installation does not rewrite its lifecycle record.
    ADD COLUMN is_available        BOOLEAN      NOT NULL DEFAULT TRUE,
    ADD COLUMN is_production_ready BOOLEAN      NOT NULL DEFAULT FALSE;

ALTER TABLE modules
    ADD CONSTRAINT ck_modules_progress CHECK (progress_percentage BETWEEN 0 AND 100);


-- =====================================================================
-- Backfill
--
-- A one-time snapshot of reality as of this migration, NOT logic: from
-- here on these are ordinary editable fields owned by administrators.
--
-- Codes are named explicitly because this is data about specific existing
-- rows — there is no rule that could infer, for example, that `knowledge`
-- has a finished backend and no screens. Every module keeps working
-- whatever value it receives; the values only change what is displayed.
-- =====================================================================

-- Baseline: every existing module has a working backend (it has been
-- running in production paths and has seeded permissions), and no
-- frontend until proven otherwise.
UPDATE modules SET
    backend_status_id  = (SELECT id FROM module_statuses WHERE code = 'BACKEND_READY' AND tenant_id IS NULL),
    frontend_status_id = (SELECT id FROM module_statuses WHERE code = 'PLANNED'       AND tenant_id IS NULL),
    progress_percentage = 50
WHERE backend_status_id IS NULL;

-- Modules that additionally have complete Vue screens today. Verified
-- against frontend/src/router/index.ts at the time of this migration.
UPDATE modules SET
    backend_status_id  = (SELECT id FROM module_statuses WHERE code = 'ACTIVE' AND tenant_id IS NULL),
    frontend_status_id = (SELECT id FROM module_statuses WHERE code = 'ACTIVE' AND tenant_id IS NULL),
    progress_percentage = 100,
    is_production_ready = TRUE
WHERE code IN ('dashboard', 'dashboards', 'users', 'roles', 'permissions',
               'modules', 'products', 'customers', 'suppliers', 'purchasing');

-- Modules whose backend is complete and verified end-to-end but which
-- have no screens yet.
UPDATE modules SET
    progress_percentage = 60
WHERE code IN ('automation', 'licensing', 'data-quality', 'metadata',
               'files', 'scheduler', 'knowledge', 'organization', 'calendar', 'appointments');

-- Built but never exercised against a running system; honest about it.
UPDATE modules SET
    backend_status_id = (SELECT id FROM module_statuses WHERE code = 'IN_DEVELOPMENT' AND tenant_id IS NULL),
    progress_percentage = 35
WHERE code = 'portal';

-- Navigation scaffolds seeded by V4 with no implementation on either side:
-- no Java package, no tables, and disabled. The baseline above assumed a
-- working backend, which is true of every module that came later but not
-- of these — left uncorrected they would claim 50% progress for code that
-- does not exist, reintroducing the dishonesty this migration removes.
UPDATE modules SET
    backend_status_id  = (SELECT id FROM module_statuses WHERE code = 'PLANNED' AND tenant_id IS NULL),
    frontend_status_id = (SELECT id FROM module_statuses WHERE code = 'PLANNED' AND tenant_id IS NULL),
    progress_percentage = 0,
    is_production_ready = FALSE
WHERE code IN ('categories', 'orders', 'reports', 'settings');

ALTER TABLE modules
    ALTER COLUMN backend_status_id  SET NOT NULL,
    ALTER COLUMN frontend_status_id SET NOT NULL;

ALTER TABLE modules
    ADD CONSTRAINT fk_modules_backend_status  FOREIGN KEY (backend_status_id)  REFERENCES module_statuses (id),
    ADD CONSTRAINT fk_modules_frontend_status FOREIGN KEY (frontend_status_id) REFERENCES module_statuses (id),
    ADD CONSTRAINT fk_modules_overall_status  FOREIGN KEY (overall_status_id)  REFERENCES module_statuses (id);

