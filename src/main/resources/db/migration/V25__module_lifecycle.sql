-- =====================================================================
-- V25 — Module lifecycle status
--
-- Makes module implementation status DATA rather than an inference.
--
-- THE PROBLEM THIS FIXES. The frontend decided whether a module was
-- "implemented" by asking its own router whether a static Vue route
-- existed for the module's path. That conflates two independent facts:
--
--     "no frontend route exists"  ⟹  "this module is not implemented"
--
-- which is wrong in both directions. Modules such as files, knowledge,
-- portal and appointments have complete schemas, services, endpoints and
-- tests but no screens; they reported themselves as un-started. A module
-- created at runtime in the admin panel, with no backend at all, reported
-- exactly the same thing. The status was never data — it was a build-time
-- property of the frontend bundle.
--
-- THE MODEL. Backend and frontend readiness are tracked as SEPARATE axes,
-- because that is what the real states look like. Overall status is
-- derived from the two unless an administrator pins it explicitly.
--
-- Derivation is data-driven via `lifecycle_rank`, not by matching status
-- codes in Java: overall is the LEAST advanced of the two axes (a module
-- is only as usable as its weakest half), except that a terminal state
-- (deprecated, retired) on either axis dominates. Reordering the lifecycle
-- or inserting a new stage is therefore a data change.
--
-- Tier S per docs/tenancy.md: a NULL tenant_id row is a platform-wide
-- default every tenant inherits.
-- =====================================================================


-- ---------------------------------------------------------------------
-- The configurable lifecycle stages.
--
-- `applies_to_backend` / `applies_to_frontend` exist because two stages
-- are axis-specific by nature: BACKEND_READY is meaningless as a frontend
-- state and FRONTEND_READY as a backend one. The admin UI offers only the
-- values valid for the axis being edited, so the pair cannot be set to a
-- nonsensical combination.
-- ---------------------------------------------------------------------
CREATE TABLE module_statuses (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code                 VARCHAR(64)  NOT NULL,
    name                 VARCHAR(100) NOT NULL,
    description          VARCHAR(500),
    color                VARCHAR(16),
    icon                 VARCHAR(64),

    -- Ordering along the lifecycle. Lower is earlier/less advanced. Gaps
    -- are deliberate so a stage can be inserted between two others
    -- without renumbering.
    lifecycle_rank       INTEGER      NOT NULL,

    applies_to_backend   BOOLEAN      NOT NULL DEFAULT TRUE,
    applies_to_frontend  BOOLEAN      NOT NULL DEFAULT TRUE,

    -- May a user open the module at all? A PLANNED module still appears
    -- in the menu (so the roadmap is visible) but need not be navigable.
    is_navigable         BOOLEAN      NOT NULL DEFAULT TRUE,

    -- Should the placeholder screen be shown instead of real content?
    -- Read from the FRONTEND axis: it is a statement about the UI.
    shows_placeholder    BOOLEAN      NOT NULL DEFAULT TRUE,

    -- Fit to appear in a production deployment.
    is_production_ready  BOOLEAN      NOT NULL DEFAULT FALSE,

    -- End of life; dominates derivation of the overall status.
    is_terminal          BOOLEAN      NOT NULL DEFAULT FALSE,

    -- Seed values for a newly created module, per axis.
    is_default_backend   BOOLEAN      NOT NULL DEFAULT FALSE,
    is_default_frontend  BOOLEAN      NOT NULL DEFAULT FALSE,

    is_system            BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order        INTEGER      NOT NULL DEFAULT 0,

    tenant_id            BIGINT,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version              BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT pk_module_statuses PRIMARY KEY (id),
    CONSTRAINT fk_module_statuses_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT ck_module_statuses_axis CHECK (applies_to_backend OR applies_to_frontend)
);
CREATE UNIQUE INDEX uq_module_statuses_code_global ON module_statuses (code) WHERE tenant_id IS NULL;
CREATE UNIQUE INDEX uq_module_statuses_code_tenant ON module_statuses (tenant_id, code) WHERE tenant_id IS NOT NULL;
CREATE UNIQUE INDEX uq_module_statuses_default_backend ON module_statuses ((TRUE))
    WHERE is_default_backend AND tenant_id IS NULL;
CREATE UNIQUE INDEX uq_module_statuses_default_frontend ON module_statuses ((TRUE))
    WHERE is_default_frontend AND tenant_id IS NULL;
CREATE INDEX ix_module_statuses_rank ON module_statuses (lifecycle_rank);


