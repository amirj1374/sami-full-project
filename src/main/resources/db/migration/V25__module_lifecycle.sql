-- =====================================================================
-- Post-migration assertions
-- =====================================================================

DO $$
DECLARE
    unassigned        BIGINT;
    default_backend   BIGINT;
    default_frontend  BIGINT;
    bad_axis          BIGINT;
BEGIN
    SELECT count(*) INTO unassigned FROM modules
    WHERE backend_status_id IS NULL OR frontend_status_id IS NULL;
    IF unassigned > 0 THEN
        RAISE EXCEPTION 'V25: % module(s) left without a lifecycle status', unassigned;
    END IF;

    SELECT count(*) INTO default_backend FROM module_statuses
    WHERE is_default_backend AND tenant_id IS NULL;
    IF default_backend <> 1 THEN
        RAISE EXCEPTION 'V25: expected exactly 1 default backend status, found %', default_backend;
    END IF;

    SELECT count(*) INTO default_frontend FROM module_statuses
    WHERE is_default_frontend AND tenant_id IS NULL;
    IF default_frontend <> 1 THEN
        RAISE EXCEPTION 'V25: expected exactly 1 default frontend status, found %', default_frontend;
    END IF;

    -- A module must never hold a status that does not apply to its axis.
    SELECT count(*) INTO bad_axis FROM modules m
    JOIN module_statuses bs ON bs.id = m.backend_status_id
    JOIN module_statuses fs ON fs.id = m.frontend_status_id
    WHERE NOT bs.applies_to_backend OR NOT fs.applies_to_frontend;
    IF bad_axis > 0 THEN
        RAISE EXCEPTION 'V25: % module(s) hold a status invalid for their axis', bad_axis;
    END IF;
END $$;
