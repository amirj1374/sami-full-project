-- User Management module: configurable statuses, extensible profiles,
-- audit log, and lifecycle (archive / soft-delete) columns.

-- Configurable user statuses. Behavior lives in flags, never in names/code:
--   allows_login       gates authentication
--   hidden_by_default  excluded from listings unless explicitly requested
--   is_default         assigned on registration, reactivation and restore (unique)
--   is_archived_state  the status the "archive" operation targets (unique)
--   is_deleted_state   the status the "soft delete" operation targets (unique)
CREATE TABLE user_statuses (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code              VARCHAR(64)  NOT NULL,
    name              VARCHAR(100) NOT NULL,
    description       VARCHAR(255),
    allows_login      BOOLEAN      NOT NULL DEFAULT FALSE,
    hidden_by_default BOOLEAN      NOT NULL DEFAULT FALSE,
    is_default        BOOLEAN      NOT NULL DEFAULT FALSE,
    is_archived_state BOOLEAN      NOT NULL DEFAULT FALSE,
    is_deleted_state  BOOLEAN      NOT NULL DEFAULT FALSE,
    is_system         BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order     INTEGER      NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_user_statuses PRIMARY KEY (id),
    CONSTRAINT uq_user_statuses_code UNIQUE (code)
);

CREATE UNIQUE INDEX uq_user_statuses_default  ON user_statuses (is_default)        WHERE is_default;
CREATE UNIQUE INDEX uq_user_statuses_archived ON user_statuses (is_archived_state) WHERE is_archived_state;
CREATE UNIQUE INDEX uq_user_statuses_deleted  ON user_statuses (is_deleted_state)  WHERE is_deleted_state;

