-- One profile per user. Standard fields are real (constrainable, indexable)
-- columns; future fields land in custom_fields (JSONB), described and validated
-- via profile_field_definitions — no schema change required.
CREATE TABLE user_profiles (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT       NOT NULL,
    first_name    VARCHAR(80),
    last_name     VARCHAR(80),
    display_name  VARCHAR(160),
    national_code VARCHAR(32),
    employee_code VARCHAR(32),
    phone_number  VARCHAR(32),
    gender        VARCHAR(16),
    birth_date    DATE,
    avatar_key    VARCHAR(255),
    address       VARCHAR(500),
    notes         VARCHAR(2000),
    custom_fields JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_user_profiles PRIMARY KEY (id),
    CONSTRAINT uq_user_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_user_profiles_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);

-- Uniqueness only applies to values that are present.
CREATE UNIQUE INDEX uq_user_profiles_phone         ON user_profiles (phone_number)  WHERE phone_number  IS NOT NULL;
CREATE UNIQUE INDEX uq_user_profiles_employee_code ON user_profiles (employee_code) WHERE employee_code IS NOT NULL;
CREATE UNIQUE INDEX uq_user_profiles_national_code ON user_profiles (national_code) WHERE national_code IS NOT NULL;

