-- Configurable custom profile fields (key, type, validation), editable at runtime.
CREATE TABLE profile_field_definitions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    field_key     VARCHAR(64)  NOT NULL,
    label         VARCHAR(100) NOT NULL,
    field_type    VARCHAR(16)  NOT NULL,   -- TEXT | NUMBER | DATE | BOOLEAN | SELECT
    required      BOOLEAN      NOT NULL DEFAULT FALSE,
    min_length    INTEGER,
    max_length    INTEGER,
    pattern       VARCHAR(255),
    options       JSONB,                   -- SELECT choices, e.g. ["A","B"]
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    display_order INTEGER      NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_profile_field_definitions PRIMARY KEY (id),
    CONSTRAINT uq_profile_field_definitions_key UNIQUE (field_key)
);

-- Append-only audit trail. Deliberately NO foreign keys: audit history must
-- survive a permanent user delete, so identifying emails are snapshotted.
CREATE TABLE user_audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT,
    user_email  VARCHAR(255),
    action      VARCHAR(64)  NOT NULL,
    actor_id    BIGINT,
    actor_email VARCHAR(255),
    old_values  JSONB,
    new_values  JSONB,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_user_audit_log PRIMARY KEY (id)
);

CREATE INDEX idx_user_audit_log_user_id    ON user_audit_log (user_id);
CREATE INDEX idx_user_audit_log_created_at ON user_audit_log (created_at);

-- Lifecycle permissions beyond the standard six, under the existing users module.
INSERT INTO permissions (module_id, action, code, name, is_system)
SELECT m.id, a.action, m.code || ':' || a.action, m.name || ' — ' || a.label, TRUE
FROM modules m
CROSS JOIN (VALUES
    ('archive', 'Archive'),
    ('restore', 'Restore'),
    ('purge',   'Permanent delete')
) AS a(action, label)
WHERE m.code = 'users';
