    CONSTRAINT pk_customer_addresses PRIMARY KEY (id),
    CONSTRAINT fk_customer_addresses_customer FOREIGN KEY (customer_id)
        REFERENCES customers (id) ON DELETE CASCADE
);
CREATE INDEX idx_customer_addresses_customer ON customer_addresses (customer_id);
CREATE INDEX idx_customer_addresses_city     ON customer_addresses (lower(city));
CREATE UNIQUE INDEX uq_customer_addresses_default
    ON customer_addresses (customer_id) WHERE is_default;

CREATE TABLE customer_tag_links (
    customer_id BIGINT NOT NULL,
    tag_id      BIGINT NOT NULL,
    CONSTRAINT pk_customer_tag_links PRIMARY KEY (customer_id, tag_id),
    CONSTRAINT fk_ctl_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT fk_ctl_tag      FOREIGN KEY (tag_id)      REFERENCES customer_tags (id) ON DELETE CASCADE
);

-- Notes: author snapshotted; PRIVATE notes are visible to their author only.
CREATE TABLE customer_notes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id  BIGINT       NOT NULL,
    author_id    BIGINT,
    author_email VARCHAR(255),
    priority     VARCHAR(16)  NOT NULL DEFAULT 'NORMAL',   -- LOW | NORMAL | HIGH
    visibility   VARCHAR(16)  NOT NULL DEFAULT 'PUBLIC',   -- PUBLIC | PRIVATE
    body         VARCHAR(4000) NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_customer_notes PRIMARY KEY (id),
    CONSTRAINT fk_customer_notes_customer FOREIGN KEY (customer_id)
        REFERENCES customers (id) ON DELETE CASCADE
);
CREATE INDEX idx_customer_notes_customer ON customer_notes (customer_id);

-- The 360° timeline. Append-only and OPEN: event_type is a free string so
-- future modules (sales, repairs, installments, payments…) record their own
-- event types here through CustomerEventService without any CRM change.
CREATE TABLE customer_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id   BIGINT       NOT NULL,
    event_type    VARCHAR(64)  NOT NULL,
    title         VARCHAR(255) NOT NULL,
    detail        JSONB,
    source_module VARCHAR(64)  NOT NULL DEFAULT 'crm',
    actor_id      BIGINT,
    actor_email   VARCHAR(255),
    occurred_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_customer_events PRIMARY KEY (id),
    CONSTRAINT fk_customer_events_customer FOREIGN KEY (customer_id)
        REFERENCES customers (id) ON DELETE CASCADE
);
CREATE INDEX idx_customer_events_customer ON customer_events (customer_id, occurred_at DESC);
CREATE INDEX idx_customer_events_type     ON customer_events (event_type);

-- Duplicate-detection policy as data: each identifier can be toggled at runtime.
CREATE TABLE crm_duplicate_rules (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    identifier VARCHAR(32) NOT NULL,   -- PHONE | EMAIL | NATIONAL_CODE | PASSPORT
    enabled    BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version    BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT pk_crm_duplicate_rules PRIMARY KEY (id),
    CONSTRAINT uq_crm_duplicate_rules_identifier UNIQUE (identifier)
);

