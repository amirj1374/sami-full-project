-- Customer Management (CRM): configurable types/statuses/sources/tags,
-- customers with multi-value contacts and addresses, notes, an append-only
-- timeline event store, duplicate-detection rules, and merge support.

-- Configurable customer types. Purely data; no type code appears in logic.
CREATE TABLE customer_types (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code          VARCHAR(64)  NOT NULL,
    name          VARCHAR(100) NOT NULL,
    description   VARCHAR(255),
    is_default    BOOLEAN      NOT NULL DEFAULT FALSE,
    is_system     BOOLEAN      NOT NULL DEFAULT FALSE,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    display_order INTEGER      NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_customer_types PRIMARY KEY (id),
    CONSTRAINT uq_customer_types_code UNIQUE (code)
);
CREATE UNIQUE INDEX uq_customer_types_default ON customer_types (is_default) WHERE is_default;

