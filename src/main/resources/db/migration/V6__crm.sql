-- The customer record. Identity fields are indexed but NOT uniquely constrained:
-- duplicate policy is data (crm_duplicate_rules), enforced in the service, so a
-- disabled rule really is disabled. merged_into_id marks records absorbed by a
-- merge — they stay resolvable forever but leave listings and duplicate checks.
CREATE TABLE customers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_code   VARCHAR(32)  NOT NULL,
    first_name      VARCHAR(80),
    last_name       VARCHAR(80),
    display_name    VARCHAR(160) NOT NULL,
    national_code   VARCHAR(32),
    passport_number VARCHAR(32),
    birth_date      DATE,
    gender          VARCHAR(16),
    occupation      VARCHAR(120),
    company_name    VARCHAR(160),
    tax_number      VARCHAR(64),
    avatar_key      VARCHAR(255),
    type_id         BIGINT       NOT NULL,
    status_id       BIGINT       NOT NULL,
    source_id       BIGINT,
    merged_into_id  BIGINT,
    archived_at     TIMESTAMPTZ,
    archived_by     BIGINT,
    deleted_at      TIMESTAMPTZ,
    deleted_by      BIGINT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_customers PRIMARY KEY (id),
    CONSTRAINT uq_customers_code UNIQUE (customer_code),
    CONSTRAINT fk_customers_type   FOREIGN KEY (type_id)   REFERENCES customer_types (id),
    CONSTRAINT fk_customers_status FOREIGN KEY (status_id) REFERENCES customer_statuses (id),
    CONSTRAINT fk_customers_source FOREIGN KEY (source_id) REFERENCES customer_sources (id),
    CONSTRAINT fk_customers_merged FOREIGN KEY (merged_into_id) REFERENCES customers (id)
);
CREATE INDEX idx_customers_status        ON customers (status_id);
CREATE INDEX idx_customers_type          ON customers (type_id);
CREATE INDEX idx_customers_national_code ON customers (national_code);
CREATE INDEX idx_customers_passport      ON customers (passport_number);
CREATE INDEX idx_customers_display_name  ON customers (lower(display_name));
CREATE INDEX idx_customers_merged_into   ON customers (merged_into_id);

-- Phones and emails: one table, discriminated by kind; at most one default per
-- (customer, kind). Modification history goes to customer_events.
CREATE TABLE customer_contacts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id BIGINT       NOT NULL,
    kind        VARCHAR(16)  NOT NULL,   -- PHONE | EMAIL
    value       VARCHAR(255) NOT NULL,
    label       VARCHAR(60),
    is_default  BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_customer_contacts PRIMARY KEY (id),
    CONSTRAINT fk_customer_contacts_customer FOREIGN KEY (customer_id)
        REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT ck_customer_contacts_kind CHECK (kind IN ('PHONE', 'EMAIL'))
);
CREATE INDEX idx_customer_contacts_customer ON customer_contacts (customer_id);
CREATE INDEX idx_customer_contacts_value    ON customer_contacts (lower(value));
CREATE UNIQUE INDEX uq_customer_contacts_default
    ON customer_contacts (customer_id, kind) WHERE is_default;

CREATE TABLE customer_addresses (
