-- Purchasing: configurable statuses/types/reasons/identifier-types/warehouses,
-- purchase documents with items, receipts, returns, serialized identifiers,
-- attachments, approval rules and an append-only purchase log.

-- Configurable purchase statuses. Structural roles are unique flagged rows;
-- behavior lives in allows_editing / allows_receiving / is_terminal.
CREATE TABLE pur_statuses (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code                VARCHAR(64)  NOT NULL,
    name                VARCHAR(100) NOT NULL,
    description         VARCHAR(255),
    allows_editing      BOOLEAN      NOT NULL DEFAULT FALSE,
    allows_receiving    BOOLEAN      NOT NULL DEFAULT FALSE,
    is_terminal         BOOLEAN      NOT NULL DEFAULT FALSE,
    is_draft_state      BOOLEAN      NOT NULL DEFAULT FALSE,
    is_pending_state    BOOLEAN      NOT NULL DEFAULT FALSE,
    is_approved_state   BOOLEAN      NOT NULL DEFAULT FALSE,
    is_partial_state    BOOLEAN      NOT NULL DEFAULT FALSE,
    is_completed_state  BOOLEAN      NOT NULL DEFAULT FALSE,
    is_cancelled_state  BOOLEAN      NOT NULL DEFAULT FALSE,
    is_rejected_state   BOOLEAN      NOT NULL DEFAULT FALSE,
    is_system           BOOLEAN      NOT NULL DEFAULT FALSE,
    display_order       INTEGER      NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_pur_statuses PRIMARY KEY (id),
    CONSTRAINT uq_pur_statuses_code UNIQUE (code)
);
CREATE UNIQUE INDEX uq_pur_statuses_draft     ON pur_statuses (is_draft_state)     WHERE is_draft_state;
CREATE UNIQUE INDEX uq_pur_statuses_pending   ON pur_statuses (is_pending_state)   WHERE is_pending_state;
CREATE UNIQUE INDEX uq_pur_statuses_approved  ON pur_statuses (is_approved_state)  WHERE is_approved_state;
CREATE UNIQUE INDEX uq_pur_statuses_partial   ON pur_statuses (is_partial_state)   WHERE is_partial_state;
CREATE UNIQUE INDEX uq_pur_statuses_completed ON pur_statuses (is_completed_state) WHERE is_completed_state;
CREATE UNIQUE INDEX uq_pur_statuses_cancelled ON pur_statuses (is_cancelled_state) WHERE is_cancelled_state;
CREATE UNIQUE INDEX uq_pur_statuses_rejected  ON pur_statuses (is_rejected_state)  WHERE is_rejected_state;

