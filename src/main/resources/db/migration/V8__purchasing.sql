-- The purchase document. Supplier references the CRM registry (single source
-- of customer/supplier truth); no supplier data is duplicated here.
CREATE TABLE purchases (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    purchase_number  VARCHAR(40)   NOT NULL,
    type_id          BIGINT        NOT NULL,
    status_id        BIGINT        NOT NULL,
    supplier_id      BIGINT        NOT NULL,
    warehouse_id     BIGINT,
    notes            VARCHAR(2000),
    total_amount     NUMERIC(14,2) NOT NULL DEFAULT 0,
    submitted_at     TIMESTAMPTZ,
    approved_at      TIMESTAMPTZ,
    approved_by      BIGINT,
    cancelled_at     TIMESTAMPTZ,
    cancelled_by     BIGINT,
    cancel_reason_id BIGINT,
    cancel_note      VARCHAR(500),
    created_by       BIGINT,
    created_by_email VARCHAR(255),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT pk_purchases PRIMARY KEY (id),
    CONSTRAINT uq_purchases_number UNIQUE (purchase_number),
    CONSTRAINT fk_purchases_type      FOREIGN KEY (type_id)      REFERENCES pur_types (id),
    CONSTRAINT fk_purchases_status    FOREIGN KEY (status_id)    REFERENCES pur_statuses (id),
    CONSTRAINT fk_purchases_supplier  FOREIGN KEY (supplier_id)  REFERENCES customers (id),
    CONSTRAINT fk_purchases_warehouse FOREIGN KEY (warehouse_id) REFERENCES pur_warehouses (id),
    CONSTRAINT fk_purchases_cancel_reason FOREIGN KEY (cancel_reason_id) REFERENCES pur_cancel_reasons (id)
);
CREATE INDEX idx_purchases_supplier ON purchases (supplier_id);
CREATE INDEX idx_purchases_status   ON purchases (status_id);
CREATE INDEX idx_purchases_type     ON purchases (type_id);
CREATE INDEX idx_purchases_created  ON purchases (created_at);

CREATE TABLE purchase_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    purchase_id       BIGINT        NOT NULL,
    product_id        BIGINT        NOT NULL,
    description       VARCHAR(500),
    quantity          NUMERIC(12,3) NOT NULL,
    unit              VARCHAR(32)   NOT NULL DEFAULT 'piece',
    unit_price        NUMERIC(12,2) NOT NULL,
    discount          NUMERIC(12,2) NOT NULL DEFAULT 0,
    expected_delivery DATE,
    requires_serial   BOOLEAN       NOT NULL DEFAULT FALSE,
    requires_imei     BOOLEAN       NOT NULL DEFAULT FALSE,
    received_quantity NUMERIC(12,3) NOT NULL DEFAULT 0,
    returned_quantity NUMERIC(12,3) NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version           BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT pk_purchase_items PRIMARY KEY (id),
    CONSTRAINT fk_pi_purchase FOREIGN KEY (purchase_id) REFERENCES purchases (id) ON DELETE CASCADE,
    CONSTRAINT fk_pi_product  FOREIGN KEY (product_id)  REFERENCES products (id),
    CONSTRAINT ck_pi_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_pi_price_non_negative CHECK (unit_price >= 0),
    CONSTRAINT ck_pi_discount_non_negative CHECK (discount >= 0),
    CONSTRAINT ck_pi_received_bounds CHECK (received_quantity >= 0 AND received_quantity <= quantity),
    CONSTRAINT ck_pi_returned_bounds CHECK (returned_quantity >= 0 AND returned_quantity <= received_quantity)
);
CREATE INDEX idx_pi_purchase ON purchase_items (purchase_id);
CREATE INDEX idx_pi_product  ON purchase_items (product_id);

-- Receipts: multiple per purchase; lines record what arrived when.
CREATE TABLE purchase_receipts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    purchase_id      BIGINT       NOT NULL,
    note             VARCHAR(500),
    created_by       BIGINT,
    created_by_email VARCHAR(255),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_purchase_receipts PRIMARY KEY (id),
    CONSTRAINT fk_pr_purchase FOREIGN KEY (purchase_id) REFERENCES purchases (id) ON DELETE CASCADE
);
CREATE INDEX idx_pr_purchase ON purchase_receipts (purchase_id);

CREATE TABLE purchase_receipt_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    receipt_id       BIGINT        NOT NULL,
    purchase_item_id BIGINT        NOT NULL,
    quantity         NUMERIC(12,3) NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT pk_purchase_receipt_items PRIMARY KEY (id),
    CONSTRAINT fk_pri_receipt FOREIGN KEY (receipt_id) REFERENCES purchase_receipts (id) ON DELETE CASCADE,
    CONSTRAINT fk_pri_item    FOREIGN KEY (purchase_item_id) REFERENCES purchase_items (id) ON DELETE CASCADE,
    CONSTRAINT ck_pri_quantity_positive CHECK (quantity > 0)
);

-- Identifiers of serialized received units (IMEI, serial, …). Values are
-- globally unique per identifier type — duplicate serials are impossible.
CREATE TABLE purchase_unit_identifiers (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    receipt_item_id    BIGINT       NOT NULL,
    unit_index         INTEGER      NOT NULL,
    identifier_type_id BIGINT       NOT NULL,
    value              VARCHAR(128) NOT NULL,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_purchase_unit_identifiers PRIMARY KEY (id),
    CONSTRAINT fk_pui_receipt_item FOREIGN KEY (receipt_item_id)
        REFERENCES purchase_receipt_items (id) ON DELETE CASCADE,
    CONSTRAINT fk_pui_type FOREIGN KEY (identifier_type_id) REFERENCES pur_identifier_types (id),
    CONSTRAINT uq_pui_type_value UNIQUE (identifier_type_id, value)
);
CREATE INDEX idx_pui_value ON purchase_unit_identifiers (value);

-- Supplier returns: multiple per purchase, partial or complete.
CREATE TABLE purchase_returns (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    purchase_id      BIGINT       NOT NULL,
    reason           VARCHAR(500) NOT NULL,
    created_by       BIGINT,
    created_by_email VARCHAR(255),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_purchase_returns PRIMARY KEY (id),
    CONSTRAINT fk_pret_purchase FOREIGN KEY (purchase_id) REFERENCES purchases (id) ON DELETE CASCADE
);
CREATE INDEX idx_pret_purchase ON purchase_returns (purchase_id);

CREATE TABLE purchase_return_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    return_id        BIGINT        NOT NULL,
    purchase_item_id BIGINT        NOT NULL,
    quantity         NUMERIC(12,3) NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT pk_purchase_return_items PRIMARY KEY (id),
    CONSTRAINT fk_preti_return FOREIGN KEY (return_id) REFERENCES purchase_returns (id) ON DELETE CASCADE,
    CONSTRAINT fk_preti_item   FOREIGN KEY (purchase_item_id) REFERENCES purchase_items (id) ON DELETE CASCADE,
    CONSTRAINT ck_preti_quantity_positive CHECK (quantity > 0)
);

-- Unlimited attachments via the FileStorage port (any content type).
CREATE TABLE purchase_attachments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    purchase_id      BIGINT       NOT NULL,
    file_key         VARCHAR(255) NOT NULL,
    file_name        VARCHAR(255) NOT NULL,
    content_type     VARCHAR(128),
    file_size        BIGINT       NOT NULL,
    uploaded_by      BIGINT,
    uploaded_by_email VARCHAR(255),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_purchase_attachments PRIMARY KEY (id),
    CONSTRAINT fk_pa_purchase FOREIGN KEY (purchase_id) REFERENCES purchases (id) ON DELETE CASCADE
);
CREATE INDEX idx_pa_purchase ON purchase_attachments (purchase_id);

-- Append-only purchase history (submit, approve, receive, cancel, return…).
CREATE TABLE purchase_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    purchase_id BIGINT       NOT NULL,
    action      VARCHAR(64)  NOT NULL,
    title       VARCHAR(255) NOT NULL,
    detail      JSONB,
    actor_id    BIGINT,
    actor_email VARCHAR(255),
    occurred_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_purchase_logs PRIMARY KEY (id),
    CONSTRAINT fk_pl_purchase FOREIGN KEY (purchase_id) REFERENCES purchases (id) ON DELETE CASCADE
);
CREATE INDEX idx_pl_purchase ON purchase_logs (purchase_id, occurred_at DESC);

